#!/usr/bin/env python3
"""gencopy.py OUT: OUT/calls7.h, call7(k, main, ...): every ARM7 kernel by a direct call, in work RAM or,
for main RAM cases, the same bytes in the cartridge image the boot stub left in main RAM (no code is
copied at run time, and every call has a constant target)."""
import os
import re

import sys

OUT = sys.argv[1]
s = open(os.path.join(OUT, "cases.h")).read()
a, b = s.split("cases7")
ROW = re.compile(r'\{"([^"]+)",\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\}')
c7 = ROW.findall(b)
assert len(c7) == int(re.search(r"NCASES7 (\d+)", s).group(1)), len(c7)
ks = sorted({int(r[1]) for r in c7})

out = ["/* generated by gencopy.py */"]
for k in ks:
    out.append(f"__attribute__((naked, noinline)) static void m7_{k}(unsigned n, unsigned b1, unsigned b2)\n{{")
    out.append(f'    __asm__ volatile("ldr r12, =k7_{k} - " BASE7_ASM " + " IMAGE7_ASM "\\n bx r12\\n .ltorg\\n");\n}}')
out.append("__attribute__((noinline)) static u32 call7(unsigned k, int main, unsigned n, unsigned b1, unsigned b2)\n{")
out.append("    switch (k) {")
for k in ks:
    out.append(f"    case {k}:")
    out.append(f"        if (main)\n            m7_{k}(n, b1, b2);\n        else\n            k7_{k}(n, b1, b2);")
    out.append(f"        return main ? (u32)k7_{k} - BASE7 + IMAGE7 : (u32)k7_{k};")
out.append("    default:\n        return 0;\n    }\n}")
open(os.path.join(OUT, "calls7.h"), "w").write("\n".join(out) + "\n")
