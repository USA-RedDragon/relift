/** @brief Where code or data lives in a configuration. */
typedef enum ct_region { CT_ROM, CT_IWRAM, CT_EWRAM, CT_VRAM, CT_PAL, CT_OAM, CT_SRAM } ct_region;

/** @brief One probe configuration: code and data regions, Game Pak wait states 0 and the prefetch enable. */
typedef struct ct_cfg {
    /** @brief Region of the kernel's code. */
    uint8_t code;
    /** @brief Region of the kernel's data. */
    uint8_t data;
    /** @brief Wait state 0 first access cycles. */
    uint8_t n;
    /** @brief Wait state 0 second access cycles. */
    uint8_t s;
    /** @brief Prefetch buffer enabled. */
    uint8_t pf;
} ct_cfg;

/** @brief One measurement: configuration, kernel and the timer's count. */
typedef struct ct_rec {
    /** @brief Index into ct_cfgs. */
    uint8_t cfg;
    /** @brief Kernel index of the probe. */
    uint8_t kernel;
    /** @brief Timer 0 and 1 count from start to stop. */
    uint32_t cycles;
} ct_rec;

