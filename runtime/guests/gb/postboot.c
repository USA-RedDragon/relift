const rl_gb_boot *rl_gb_boot_state(rl_gb_model model, bool color_mode)
{
    if ((unsigned)model >= RL_GB_MODELS)
        return NULL;
    bool want = color_mode && rl_gb_model_is_cgb(model);
    for (size_t i = 0; i < sizeof table / sizeof table[0]; i++)
        if (table[i].model == model && table[i].color_mode == want)
            return &table[i];
    return NULL;
}

static unsigned popcount8(uint8_t v)
{
    unsigned n = 0;
    for (; v; v &= (uint8_t)(v - 1))
        n++;
    return n;
}

void rl_gb_boot_state_for(rl_gb_model model, bool color_mode, const uint8_t *rom, size_t len, rl_gb_boot *out)
{
    *out = *rl_gb_boot_state(model, color_mode);
    if (!rom || len < 0x150)
        return;
    if (model == RL_GB_DMG || model == RL_GB_MGB) {
        uint8_t sum = rom[0x14D];
        out->f = (uint8_t)(0x80u | ((sum & 0xFu) ? 0x20u : 0u) | (sum ? 0x10u : 0u));
    } else if (model == RL_GB_SGB || model == RL_GB_SGB2) {
        unsigned bits = 0;
        for (unsigned a = 0x104; a <= 0x14F; a++)
            bits += popcount8(rom[a]);
        out->div_counter = (uint16_t)(0xDC88u - 4u * bits);
        out->io[0x04] = (uint8_t)(out->div_counter >> 8);
    }
}

const rl_gb_boot *rl_gb_boot_of(const rl_gb *g) { return &g->boot; }

void gb_seed_stubs(rl_gb *g)
{
    for (unsigned i = 0; i < RL_GB_SLOTS; i++) {
        memcpy(g->stub[i].regs, g->boot.io, sizeof g->boot.io);
        g->stub[i].regs[0xFF] = g->boot.ie;
    }
}

void rl_gb_reset(rl_gb *g)
{
    rl_gb_boot_state_for(g->model, g->color, g->cart.rom, g->cart.rom_len, &g->boot);
    g->vbk = 0;
    g->svbk = 0;
    gb_reset_mapper(g);
    if (g->sched)
        gb_seed_stubs(g);
}
