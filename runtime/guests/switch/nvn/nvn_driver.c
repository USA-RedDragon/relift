/**
 * @file nvn_driver.c
 * @brief The NVN2 procs that stay the SDK driver's own code.
 *
 * Builders, state objects and texture views: their driver functions only
 * read and write the object they are given and the driver's read-only
 * tables (no calls out of the driver, no stores to driver globals, no system
 * registers), so the game's lifted copy of them runs as it is. relift's
 * procs read such objects back through the driver's getters, so they never
 * depend on the driver's private layout. The DLSS network builder and
 * parameter procs here are plain loads and stores on their object (verified:
 * SDK 22.2.0 driver); creating, resizing and evaluating a network are not.
 * Texture getters that read what the driver's own nvnTextureInitialize
 * stores in a texture also stay: they read the texture and the device fields
 * the layer writes for that initialization. The list is sorted (strcmp
 * order).
 */
