int nvn_driver_index(const char *name)
{
    uint32_t lo = 0, hi = NVN_DRIVER_PROC_COUNT;
    while (lo < hi) {
        uint32_t mid = (lo + hi) / 2;
        int c = strcmp(driver_procs[mid], name);
        if (!c)
            return (int)mid;
        if (c < 0)
            lo = mid + 1;
        else
            hi = mid;
    }
    return -1;
}

bool nvn_driver_reads_texture(const char *name)
{
    static const char *const getters[] = { "nvnTextureGetRawStorageClass", "nvnTextureGetSparseTileLayout",
                                           "nvnTextureGetStorageClass" };
    for (size_t i = 0; i < sizeof getters / sizeof getters[0]; i++)
        if (name && !strcmp(name, getters[i]))
            return true;
    return false;
}
