//! Generates the A64 lifting templates in `cpus/a64/src/lift/sail/generated`
//! from the sail-arm model. Run it only to regenerate; normal builds use the
//! committed output.
//!
//! ```text
//! relift-cpu-a64-gen classes
//! relift-cpu-a64-gen parse-all SAIL_LIB MODEL_SRC
//! relift-cpu-a64-gen try SAIL_LIB MODEL_SRC ENCODING...
//! relift-cpu-a64-gen gen SAIL_LIB MODEL_SRC ENCODING_LIST CLASS > OUT
//! ```
//!
//! `SAIL_LIB` is the `lib` directory of the Sail compiler sources and
//! `MODEL_SRC` the `arm-v9.4-a/src` directory of sail-arm. `gen` prints the
//! templates of the listed encodings in one class ([`CLASSES`]), the file
//! `cpus/a64/src/lift/sail/generated/CLASS.rs`.

mod ast;
mod builtins;
mod cut;
mod eval;
mod model;
mod ops;
mod parse;
mod template;
mod value;

use std::fmt::Write as _;
use std::process::ExitCode;

use relift_cpu_a64::decode::Encoding;

fn main() -> ExitCode {
    let run = std::thread::Builder::new()
        .stack_size(256 << 20)
        .spawn(real_main)
        .expect("spawns the worker thread");
    run.join().expect("worker finishes")
}

fn by_name(n: &str) -> Option<Encoding> {
    Encoding::all().find(|e| e.name() == n)
}

/// The sail-arm commit the committed output is generated from.
const SAIL_ARM: &str = "5416ef6b43e9527c38dc71fb752259c1d01a47e1";

/// The rems-project/sail commit whose `lib` the generator reads.
const SAIL_LIB: &str = "c44944f11b71e5c9bd4b30cdbf79ea32f6dcf456";

/// The output files, one per instruction class.
const CLASSES: [&str; 15] = [
    "int",
    "ldst",
    "excl",
    "branch",
    "system",
    "simd_ldst_multi",
    "simd_ldst_multi_post",
    "simd_ldst_single",
    "simd_same",
    "simd_same_ext",
    "simd_shift",
    "simd_misc",
    "simd_elem",
    "simd_other",
    "fp",
];

/// The class of an encoding, from its AARCHMRS name.
fn class_of(name: &str) -> &'static str {
    let has = |s: &str| name.contains(s);
    if has("float") {
        "fp"
    } else if has("asimd") || has("asisd") || has("crypto") {
        simd_class(name)
    } else if has("_ldstexclr") || has("_ldstord") {
        "excl"
    } else if has("_ldst") || has("loadlit") {
        "ldst"
    } else if has("branch") {
        "branch"
    } else if has("hints") || has("barriers") || has("system") || has("exception") || has("pstate")
    {
        "system"
    } else {
        "int"
    }
}

/// The file of a SIMD encoding, by its AARCHMRS group, so no file grows
/// past about 2 MB.
fn simd_class(name: &str) -> &'static str {
    let group = name
        .split('_')
        .find(|p| p.starts_with("asimd") || p.starts_with("asisd") || p.starts_with("crypto"))
        .unwrap_or("");
    match group {
        "asisdlse" => "simd_ldst_multi",
        "asisdlsep" => "simd_ldst_multi_post",
        "asisdlso" | "asisdlsop" => "simd_ldst_single",
        g if g.starts_with("asimdsame2")
            || g.starts_with("asisdsame2")
            || g.ends_with("fp16")
                && (g.starts_with("asimdsame") || g.starts_with("asisdsame")) =>
        {
            "simd_same_ext"
        }
        g if g.starts_with("asimdsame") || g.starts_with("asisdsame") => "simd_same",
        "asimdshf" | "asisdshf" => "simd_shift",
        g if g.starts_with("asimdmisc")
            || g.starts_with("asisdmisc")
            || g == "asimdall"
            || g == "asisdpair"
            || g == "asisdone" =>
        {
            "simd_misc"
        }
        "asimdelem" | "asisdelem" => "simd_elem",
        _ => "simd_other",
    }
}

fn header(class: &str) -> String {
    format!(
        "//! Generated by relift-cpu-a64-gen {} from sail-arm {SAIL_ARM} and the Sail
//! library at {SAIL_LIB}: the `{class}` templates. Do not edit; see
//! `cpus/a64/gen/README.md` to regenerate. Derived from sail-arm
//! (BSD-3-Clause-Clear, see `NOTICE-sail-arm` next to this crate's
//! manifest); the Sail library parts are BSD-2-Clause.

#![allow(non_snake_case, unused, clippy::all)]

use relift_ir::{{AtomicOp, BinOp, Builder, CmpOp, CryptoOp, Endian, FpOp, FpRound, Order, UnOp, Width}};

use crate::decode::{{Encoding, Feature}};
use crate::lift::LiftError;
use crate::lift::sail::{{GenFn, half}};
use crate::lift::sail::rt::{{self, Kind, St, Target}};
use crate::regs;
",
        env!("CARGO_PKG_VERSION")
    )
}

fn real_main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.len() == 1 && args[0] == "classes" {
        return print_classes();
    }
    if args.len() < 3 {
        eprintln!("usage: see the crate documentation");
        return ExitCode::from(2);
    }
    let m = match model::Model::load(args[1].as_ref(), args[2].as_ref()) {
        Ok(m) => m,
        Err(e) => {
            eprintln!("cannot load the model: {e}");
            return ExitCode::FAILURE;
        }
    };
    if matches!(args[0].as_str(), "try" | "gen")
        && let Err(e) = cut::verify_crypto(&m)
    {
        eprintln!("the cipher cut differs from the model: {e}");
        return ExitCode::FAILURE;
    }
    match args[0].as_str() {
        "parse-all" => {
            let (ok, bad) = m.parse_all();
            println!("{ok} functions parsed, {} failed", bad.len());
            for (name, err) in bad.iter().take(40) {
                println!("  {name}: {err}");
            }
            ExitCode::SUCCESS
        }
        "try" => {
            for n in &args[3..] {
                let Some(enc) = by_name(n) else {
                    println!("{n}: no such encoding");
                    continue;
                };
                match template::template(&m, enc) {
                    Ok(t) => println!("{}", t.code),
                    Err(e) => println!("{n}: FAIL {e}"),
                }
            }
            ExitCode::SUCCESS
        }
        "gen" if args.len() == 5 && CLASSES.contains(&args[4].as_str()) => {
            let class = args[4].as_str();
            let list = std::fs::read_to_string(&args[3]).expect("reads the encoding list");
            let mut names: Vec<&str> = list
                .lines()
                .map(str::trim)
                .filter(|l| !l.is_empty() && !l.starts_with('#'))
                .collect();
            names.sort();
            names.dedup();
            names.retain(|n| class_of(n) == class);
            let mut body = header(class);
            let mut table = String::new();
            let (mut ok, mut bad) = (0, 0);
            for n in names {
                let Some(enc) = by_name(n) else {
                    eprintln!("{n}: no such encoding");
                    bad += 1;
                    continue;
                };
                match template::template(&m, enc) {
                    Ok(t) => {
                        body.push('\n');
                        body.push_str(&t.code);
                        let _ = writeln!(table, "Encoding::{n} => {n},");
                        ok += 1;
                    }
                    Err(e) => {
                        eprintln!("{n}: {e}");
                        bad += 1;
                    }
                }
            }
            body.push_str(
                "\n/// The generated template of `enc`, if there is one.\npub(crate) fn template(enc: Encoding) -> Option<GenFn> {\nSome(match enc {\n",
            );
            body.push_str(&table);
            body.push_str("_ => return None,\n})\n}\n");
            print!("{body}");
            eprintln!("{ok} templates generated, {bad} failed");
            if bad == 0 {
                ExitCode::SUCCESS
            } else {
                ExitCode::FAILURE
            }
        }
        _ => {
            eprintln!("usage: see the crate documentation");
            ExitCode::from(2)
        }
    }
}

/// `relift-cpu-a64-gen classes` prints the class names, one per line.
fn print_classes() -> ExitCode {
    for c in CLASSES {
        println!("{c}");
    }
    ExitCode::SUCCESS
}
