//! Generates the SM83 lifting templates in
//! `cpus/sm83/src/lift/sail/generated.rs` from the Sail model in
//! `cpus/sm83/sail/sm83.sail`. Run it only to regenerate; normal builds use
//! the committed output.
//!
//! ```text
//! relift-cpu-sm83-gen gen SAIL_LIB MODEL > OUT
//! relift-cpu-sm83-gen try SAIL_LIB MODEL OPCODE...
//! ```
//!
//! `SAIL_LIB` is the `lib` directory of the Sail compiler sources (the
//! operators and builtins the model uses), as `cpus/a64/gen/fetch-sail.sh`
//! downloads it; `MODEL` is `cpus/sm83/sail/sm83.sail`.
//!
//! `OPCODE` is a hex byte, or `cb` and a hex byte for the CB page.

mod cut;

use std::fmt::Write as _;
use std::path::Path;
use std::process::ExitCode;

use relift_cpu_sm83::{BASE, CB, Mnemonic};
use relift_sail::model::Model;
use relift_sail::stage::{self, Form};

use cut::Sm83;

/// One opcode: its page and byte.
struct Op {
    cb: bool,
    code: u8,
}

impl Op {
    fn all() -> impl Iterator<Item = Op> {
        let base = (0..=255u8).map(|code| Op { cb: false, code });
        let cb = (0..=255u8).map(|code| Op { cb: true, code });
        base.chain(cb).filter(|o| {
            let m = if o.cb { CB } else { BASE }[usize::from(o.code)].mnemonic;
            !matches!(m, Mnemonic::Illegal | Mnemonic::Prefix)
        })
    }

    fn parse(s: &str) -> Option<Op> {
        let (cb, hex) = match s.strip_prefix("cb") {
            Some(h) => (true, h),
            None => (false, s),
        };
        let code = u8::from_str_radix(hex, 16).ok()?;
        Some(Op { cb, code })
    }
}

impl Form for Op {
    fn name(&self) -> String {
        format!("{}{:02X}", if self.cb { "Cb" } else { "Op" }, self.code)
    }

    fn mask(&self) -> u32 {
        0xFF
    }

    fn value(&self) -> u32 {
        u32::from(self.code)
    }

    fn word_bits(&self) -> u32 {
        8
    }

    fn group(&self) -> Option<&'static str> {
        Some(if self.cb {
            "__DecodeSM83_CB"
        } else {
            "__DecodeSM83"
        })
    }

    fn reachable(&self, _known: u32, _value: u32) -> bool {
        true
    }
}

fn load(lib: &str, path: &str) -> Result<Model, String> {
    let model = Path::new(path);
    let dir = model.parent().unwrap_or(Path::new("."));
    let file = model
        .file_name()
        .and_then(|f| f.to_str())
        .ok_or_else(|| format!("{path}: not a file"))?;
    Model::load(Path::new(lib), dir, &[file]).map_err(|e| format!("{path}: {e}"))
}

const HEADER: &str = "\
//! Generated by relift-cpu-sm83-gen from `cpus/sm83/sail/sm83.sail`: one
//! lifting template per defined opcode. Do not edit; see
//! `cpus/sm83/gen/README.md` to regenerate.

#![allow(non_snake_case, unused, clippy::all)]

use relift_ir::{BinOp, Builder, CmpOp, UnOp, Width};

use super::rt::{self, Irq, Kind, LiftError, St, Target};
use crate::regs;

";

fn generate(m: &Model) -> Result<String, String> {
    let mut out = String::from(HEADER);
    let ops: Vec<Op> = Op::all().collect();
    out.push_str("/// The opcodes with a template.\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Encoding {\n");
    for o in &ops {
        let _ = writeln!(out, "    /// `{}`.\n    {},", o.name(), o.name());
    }
    out.push_str("}\n\n");
    let mut failed = Vec::new();
    for o in &ops {
        match stage::template::<Sm83>(m, o) {
            Ok(t) => {
                out.push_str(&t.code);
                out.push('\n');
            }
            Err(e) => failed.push(format!("{}: {e}", o.name())),
        }
    }
    eprintln!(
        "{} templates generated, {} failed",
        ops.len() - failed.len(),
        failed.len()
    );
    if !failed.is_empty() {
        return Err(failed.join("\n"));
    }
    for (cb, f) in [(false, "base"), (true, "cb")] {
        let _ = writeln!(
            out,
            "/// The template of {} opcode `code`, if it is defined.",
            if cb { "CB-prefixed" } else { "base" }
        );
        let _ = writeln!(
            out,
            "pub(super) fn {f}(code: u8) -> Option<super::GenFn> {{"
        );
        out.push_str("    Some(match code {\n");
        for o in ops.iter().filter(|o| o.cb == cb) {
            let _ = writeln!(out, "        {:#04x} => {},", o.code, o.name());
        }
        out.push_str("        _ => return None,\n    })\n}\n\n");
    }
    Ok(out)
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().collect();
    let usage = || {
        eprintln!("usage: relift-cpu-sm83-gen gen SAIL_LIB MODEL | try SAIL_LIB MODEL OPCODE...");
        ExitCode::from(2)
    };
    if args.len() < 4 {
        return usage();
    }
    let m = match load(&args[2], &args[3]) {
        Ok(m) => m,
        Err(e) => {
            eprintln!("{e}");
            return ExitCode::FAILURE;
        }
    };
    match args[1].as_str() {
        "gen" => match generate(&m) {
            Ok(text) => {
                print!("{text}");
                ExitCode::SUCCESS
            }
            Err(e) => {
                eprintln!("{e}");
                ExitCode::FAILURE
            }
        },
        "try" => {
            for a in &args[4..] {
                let Some(o) = Op::parse(a) else {
                    println!("{a}: not an opcode");
                    continue;
                };
                match stage::template::<Sm83>(&m, &o) {
                    Ok(t) => println!("{}", t.code),
                    Err(e) => println!("{}: {e}", o.name()),
                }
            }
            ExitCode::SUCCESS
        }
        _ => usage(),
    }
}
