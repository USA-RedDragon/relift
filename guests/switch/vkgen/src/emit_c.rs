//! `vkg.h`, `vkg_convert.c` and `vkg_thunks.c`: the command table, the
//! guest-to-host struct converters and one thunk per guest command.
//!
//! The thunks have the lifted-code signature and read their arguments the
//! way AAPCS64 passes them: integers and pointers in x0 to x7, floats in s0 to
//! s7, the rest in 8-byte stack slots from the guest sp. Guest pointers are
//! guest addresses; a pointer to data the host can read in place becomes
//! `mem + addr`, anything holding a pointer, a size_t, a dispatchable handle
//! or a function pointer is copied into a per-call arena with its pointers
//! translated, and copied back after the call when the host writes it.

use std::fmt::Write;

use crate::Error;
use crate::emit_types::type_text;
use crate::model::Model;
use crate::registry::{Command, Decl, Kind};
use crate::select::Audience;

const HEAD: &str = "/* Generated by relift-vkgen from vk.xml. Do not edit. */";

/// The three generated C files.
pub struct CFiles {
    /// `vkg.h`.
    pub header: String,
    /// `vkg_convert.c`.
    pub convert: String,
    /// `vkg_thunks.c`.
    pub thunks: String,
}

fn level(m: &Model, c: &Command) -> u8 {
    match c.params.first().map(|p| m.canon(&p.ty)) {
        Some("VkInstance" | "VkPhysicalDevice") if c.params[0].ptr == 0 => 1,
        Some("VkDevice" | "VkQueue" | "VkCommandBuffer") if c.params[0].ptr == 0 => 2,
        _ => 0,
    }
}

fn is_hand_struct(m: &Model, t: &str) -> bool {
    m.cfg.hand_structs.iter().any(|h| h == t)
}

fn dropped(m: &Model, t: &str) -> bool {
    m.cfg.drop_types.iter().any(|h| h == m.canon(t))
}

fn in_fn(m: &Model, t: &str) -> String {
    if is_hand_struct(m, t) {
        format!("vkh_in_{t}")
    } else {
        format!("vkg_in_{t}")
    }
}

fn out_fn(m: &Model, t: &str) -> String {
    if is_hand_struct(m, t) {
        format!("vkh_out_{t}")
    } else {
        format!("vkg_out_{t}")
    }
}

/// Translates a `len` attribute to a C expression; `field` maps a name to its value expression.
fn len_expr(
    len: Option<&str>,
    field: &dyn Fn(&str) -> Option<String>,
) -> Result<Option<String>, Error> {
    let Some(len) = len else { return Ok(None) };
    let first = len.split(',').next().unwrap_or("");
    if first == "null-terminated" {
        return Ok(None);
    }
    if let Some((p, mem)) = first.split_once("->") {
        let base = field(p).ok_or_else(|| Error(format!("len {len}: unknown {p}")))?;
        return Ok(Some(format!("({base} ? (uint64_t)({base})->{mem} : 0)")));
    }
    field(first)
        .map(Some)
        .ok_or_else(|| Error(format!("len {len} is not a supported expression")))
}

/// Emits the converters of one struct.
fn emit_struct(m: &mut Model, t: &str, o: &mut String) -> Result<(), Error> {
    let l = m.struct_layout(t)?;
    let size = l.layout.size;
    let members = m.members(t);
    let union = matches!(m.kind(t), Some(Kind::Struct { union: true, .. }));
    if union {
        return Err(Error(format!(
            "union {t} needs conversion; its active member is unknown"
        )));
    }
    let hand = is_hand_struct(m, t);
    if !hand {
        writeln!(o, "void vkg_in_{t}(vkf_call *k, {t} *h, uint64_t g)\n{{").ok();
        writeln!(o, "    memcpy(h, k->mem + g, sizeof *h);").ok();
        for (d, off) in members.iter().zip(&l.offsets) {
            let mt = m.canon(&d.ty).to_string();
            let n = &d.name;
            let field = |x: &str| {
                members
                    .iter()
                    .find(|q| q.name == x)
                    .map(|_| format!("h->{x}"))
            };
            let elems = m.elems(d)?;
            let gv = format!("vkf_g64(k, g + {off})");
            if d.ptr == 0 {
                if m.kind_of(&mt) != 0 {
                    let kind = format!("VKG_KIND_{mt}");
                    if elems == 1 {
                        writeln!(o, "    h->{n} = ({mt})vkf_unwrap(k, {kind}, {gv});").ok();
                    } else {
                        writeln!(
                            o,
                            "    for (uint32_t i = 0; i < {elems}; i++)\n        h->{n}[i] = ({mt})vkf_unwrap(k, {kind}, vkf_g64(k, g + {off} + 8 * i));"
                        )
                        .ok();
                    }
                } else if matches!(m.kind(&mt), Some(Kind::FuncPtr { .. })) {
                    return Err(Error(format!(
                        "{t}.{n} is a function pointer: list {t} in hand_structs"
                    )));
                } else if m.is_struct(&mt) && !m.plain(&mt) {
                    let es = m.struct_layout(&mt)?.layout.size;
                    if d.array.len() > 1 {
                        return Err(Error(format!("{t}.{n}: multi-dimensional struct array")));
                    }
                    if elems == 1 {
                        writeln!(o, "    {}(k, &h->{n}, g + {off});", in_fn(m, &mt)).ok();
                    } else {
                        writeln!(
                            o,
                            "    for (uint32_t i = 0; i < {elems}; i++)\n        {}(k, &h->{n}[i], g + {off} + {es} * i);",
                            in_fn(m, &mt)
                        )
                        .ok();
                    }
                }
                continue;
            }
            if n == "pNext" {
                writeln!(o, "    h->pNext = vkg_chain_in(k, {gv});").ok();
                continue;
            }
            let tt = type_text(d);
            if d.ptr == 1 && dropped(m, &mt) {
                writeln!(o, "    h->{n} = NULL;").ok();
            } else if d.ptr == 1 && (mt == "void" || mt == "size_t" || m.plain(&mt)) {
                writeln!(o, "    h->{n} = ({tt})vkf_ptr(k, {gv});").ok();
            } else if d.ptr == 1 && m.kind_of(&mt) != 0 {
                let cnt = len_expr(d.len.as_deref(), &field)?.unwrap_or_else(|| "1".into());
                writeln!(
                    o,
                    "    h->{n} = ({tt})vkf_unwrap_n(k, VKG_KIND_{mt}, {gv}, {cnt});"
                )
                .ok();
            } else if d.ptr == 1 && m.is_struct(&mt) {
                let cnt = len_expr(d.len.as_deref(), &field)?.unwrap_or_else(|| "1".into());
                writeln!(o, "    h->{n} = vkg_ain_{mt}(k, {gv}, {cnt});").ok();
            } else if d.ptr == 2 && mt == "char" && d.pointee_const {
                let cnt = len_expr(d.len.as_deref(), &field)?
                    .ok_or_else(|| Error(format!("{t}.{n}: string array without a count")))?;
                writeln!(o, "    h->{n} = vkf_strv(k, {gv}, {cnt});").ok();
            } else {
                return Err(Error(format!("{t}.{n} ({}) has no conversion", d.text)));
            }
        }
        writeln!(o, "}}\n").ok();
        writeln!(
            o,
            "void vkg_out_{t}(vkf_call *k, uint64_t g, const {t} *h)\n{{"
        )
        .ok();
        let mut run: Option<(u64, u64)> = None;
        let flush = |run: &mut Option<(u64, u64)>, o: &mut String| {
            if let Some((a, b)) = run.take()
                && b > a
            {
                writeln!(
                    o,
                    "    memcpy(k->mem + g + {a}, (const uint8_t *)h + {a}, {});",
                    b - a
                )
                .ok();
            }
        };
        let mut any = false;
        for (d, off) in members.iter().zip(&l.offsets) {
            let mt = m.canon(&d.ty).to_string();
            let n = &d.name;
            let sz = m.decl_layout(d)?.size;
            let elems = m.elems(d)?;
            let copy = d.ptr == 0
                && n != "sType"
                && m.kind_of(&mt) == 0
                && !(m.is_struct(&mt) && !m.plain(&mt));
            if copy {
                run = match run {
                    Some((a, _)) => Some((a, off + sz)),
                    None => Some((*off, off + sz)),
                };
                continue;
            }
            flush(&mut run, o);
            if n == "pNext" && d.ptr > 0 {
                writeln!(o, "    vkg_chain_out(k, vkf_g64(k, g + {off}), h->pNext);").ok();
                any = true;
            } else if d.ptr == 0 && m.kind_of(&mt) != 0 {
                let kind = format!("VKG_KIND_{mt}");
                if elems == 1 {
                    writeln!(o, "    vkf_s64(k, g + {off}, vkf_wrap(k, {kind}, h->{n}));").ok();
                } else {
                    writeln!(
                        o,
                        "    for (uint32_t i = 0; i < {elems}; i++)\n        vkf_s64(k, g + {off} + 8 * i, vkf_wrap(k, {kind}, h->{n}[i]));"
                    )
                    .ok();
                }
                any = true;
            } else if d.ptr == 0 && m.is_struct(&mt) {
                let es = m.struct_layout(&mt)?.layout.size;
                if elems == 1 {
                    writeln!(o, "    {}(k, g + {off}, &h->{n});", out_fn(m, &mt)).ok();
                } else {
                    writeln!(
                        o,
                        "    for (uint32_t i = 0; i < {elems}; i++)\n        {}(k, g + {off} + {es} * i, &h->{n}[i]);",
                        out_fn(m, &mt)
                    )
                    .ok();
                }
                any = true;
            }
        }
        if run.is_some() {
            any = true;
        }
        flush(&mut run, o);
        if !any {
            writeln!(o, "    (void)k;\n    (void)g;\n    (void)h;").ok();
        }
        writeln!(o, "}}\n").ok();
    }
    writeln!(
        o,
        "{t} *vkg_ain_{t}(vkf_call *k, uint64_t g, uint64_t n)\n{{\n    if (!g)\n        return NULL;\n    {t} *h = vkf_alloc(k, (n ? n : 1) * sizeof *h);\n    for (uint64_t i = 0; i < n; i++)\n        {}(k, &h[i], g + {size} * i);\n    return h;\n}}\n",
        in_fn(m, t)
    )
    .ok();
    writeln!(
        o,
        "void vkg_aout_{t}(vkf_call *k, uint64_t g, const {t} *h, uint64_t n)\n{{\n    if (!g || !h)\n        return;\n    for (uint64_t i = 0; i < n; i++)\n        {}(k, g + {size} * i, &h[i]);\n}}\n",
        out_fn(m, t)
    )
    .ok();
    Ok(())
}

/// Where AAPCS64 puts each parameter: x registers, s registers or stack slots.
fn arg_sources(m: &Model, c: &Command) -> Result<Vec<String>, Error> {
    let (mut x, mut v, mut s) = (0, 0, 0);
    let mut out = Vec::new();
    for p in &c.params {
        let t = m.canon(&p.ty);
        let float = p.ptr == 0 && p.array.is_empty() && t == "float";
        if p.ptr == 0 && p.array.is_empty() && (t == "double" || m.is_struct(t)) {
            return Err(Error(format!(
                "{}: {} by value is not supported",
                c.name, p.text
            )));
        }
        if float && v < 8 {
            out.push(format!("vkf_s(&k, {v})"));
            v += 1;
        } else if !float && x < 8 {
            out.push(format!("c->x[{x}]"));
            x += 1;
        } else if float {
            out.push(format!("vkf_fstack(&k, {s})"));
            s += 1;
        } else {
            out.push(format!("vkf_stack(&k, {s})"));
            s += 1;
        }
    }
    Ok(out)
}

/// Emits one generated thunk.
fn emit_thunk(m: &mut Model, def: &str, primary: &str, o: &mut String) -> Result<(), Error> {
    let c = m.reg.commands[def].clone();
    let src = arg_sources(m, &c)?;
    writeln!(
        o,
        "static int vkt_{primary}(rl_ctx *restrict c, uint8_t *mem)\n{{"
    )
    .ok();
    writeln!(o, "    vkf_call k;\n    vkf_begin(&k, c, mem);").ok();
    let lvl = level(m, &c);
    let names: Vec<String> = c.params.iter().map(|p| p.name.clone()).collect();
    let mut after: Vec<String> = Vec::new();
    let mut gated: Vec<String> = Vec::new();
    for (i, p) in c.params.iter().enumerate() {
        let t = m.canon(&p.ty).to_string();
        let s = &src[i];
        let tt = type_text(p);
        let field = |x: &str| -> Option<String> {
            let j = names.iter().position(|n| n == x)?;
            let q = &c.params[j];
            Some(if q.ptr == 1 {
                format!("(a{j} ? *a{j} : 0)")
            } else {
                format!("a{j}")
            })
        };
        let field_base = |x: &str| -> Option<String> {
            let j = names.iter().position(|n| n == x)?;
            Some(format!("a{j}"))
        };
        let lenf = |x: &str| -> Option<String> {
            if names.iter().any(|n| n == x) {
                field(x)
            } else {
                None
            }
        };
        let len = |d: &Decl| -> Result<Option<String>, Error> {
            let Some(l) = d.len.as_deref() else {
                return Ok(None);
            };
            let first = l.split(',').next().unwrap_or("");
            if let Some((p, _)) = first.split_once("->") {
                return len_expr(Some(l), &|x| if x == p { field_base(x) } else { None });
            }
            len_expr(Some(l), &lenf)
        };
        if p.ptr == 0 && p.array.is_empty() {
            if m.kind_of(&t) != 0 {
                let kind = format!("VKG_KIND_{t}");
                if i == 0 {
                    writeln!(o, "    {t} a0 = ({t})vkf_first(&k, {kind}, {s});").ok();
                    writeln!(
                        o,
                        "    if (!a0)\n        return vkf_bad_handle(&k, VKG_{primary}, {s});"
                    )
                    .ok();
                } else {
                    writeln!(o, "    {t} a{i} = ({t})vkf_unwrap(&k, {kind}, {s});").ok();
                }
                continue;
            }
            let l = m.type_layout(&t)?;
            if matches!(m.kind(&t), Some(Kind::Handle { .. })) {
                writeln!(o, "    {tt} a{i} = ({tt})(uintptr_t)({s});").ok();
            } else if t == "float" {
                writeln!(o, "    float a{i} = {s};").ok();
            } else if l.size == 8 {
                writeln!(o, "    {tt} a{i} = ({tt})({s});").ok();
            } else if t == "int32_t" {
                writeln!(o, "    int32_t a{i} = (int32_t)(uint32_t)({s});").ok();
            } else if l.size == 4 && tt == "uint32_t" {
                writeln!(o, "    uint32_t a{i} = (uint32_t)({s});").ok();
            } else if l.size == 4 {
                writeln!(o, "    {tt} a{i} = ({tt})(uint32_t)({s});").ok();
            } else {
                return Err(Error(format!(
                    "{}: parameter {} has an unsupported size",
                    c.name, p.text
                )));
            }
            continue;
        }
        let ptr_tt = if p.array.is_empty() {
            tt.clone()
        } else {
            format!("{} *", tt)
        };
        let ptr = p.ptr.max(1);
        if ptr == 1 && dropped(m, &t) {
            writeln!(o, "    {ptr_tt} a{i} = NULL;").ok();
        } else if ptr == 1 && (t == "void" || t == "size_t" || m.plain(&t)) {
            writeln!(o, "    {ptr_tt} a{i} = ({ptr_tt})vkf_ptr(&k, {s});").ok();
        } else if ptr == 1 && m.kind_of(&t) != 0 {
            let kind = format!("VKG_KIND_{t}");
            let n = len(p)?.unwrap_or_else(|| "1".into());
            if p.pointee_const {
                writeln!(
                    o,
                    "    {ptr_tt} a{i} = ({ptr_tt})vkf_unwrap_n(&k, {kind}, {s}, {n});"
                )
                .ok();
            } else {
                writeln!(o, "    uint64_t n{i} = {n};").ok();
                writeln!(
                    o,
                    "    {t} *a{i} = {s} ? vkf_alloc(&k, (n{i} ? n{i} : 1) * sizeof *a{i}) : NULL;"
                )
                .ok();
                gated.push(format!(
                    "    if (a{i}) {{\n        uint64_t w{i} = {n};\n        for (uint64_t j = 0; j < w{i} && j < n{i}; j++)\n            vkf_s64(&k, {s} + 8 * j, vkf_wrap(&k, {kind}, a{i}[j]));\n    }}"
                ));
            }
        } else if ptr == 1 && m.is_struct(&t) {
            let n = len(p)?.unwrap_or_else(|| "1".into());
            if p.pointee_const {
                writeln!(o, "    {ptr_tt} a{i} = vkg_ain_{t}(&k, {s}, {n});").ok();
            } else {
                writeln!(o, "    uint64_t n{i} = {n};").ok();
                writeln!(o, "    {t} *a{i} = vkg_ain_{t}(&k, {s}, n{i});").ok();
                gated.push(format!(
                    "    {{\n        uint64_t w{i} = {n};\n        vkg_aout_{t}(&k, {s}, a{i}, w{i} < n{i} ? w{i} : n{i});\n    }}"
                ));
            }
        } else if ptr == 2 && t == "char" && p.pointee_const {
            let n = len(p)?
                .ok_or_else(|| Error(format!("{}: string array without a count", c.name)))?;
            writeln!(o, "    {ptr_tt} a{i} = vkf_strv(&k, {s}, {n});").ok();
        } else {
            return Err(Error(format!(
                "{}: parameter {} has no conversion; list the command in hand_commands",
                c.name, p.text
            )));
        }
    }
    if lvl == 0 {
        writeln!(o, "    vkf_global(&k);").ok();
    }
    writeln!(
        o,
        "    PFN_{primary} fn = (PFN_{primary})k.fns->f[VKG_{primary}];"
    )
    .ok();
    writeln!(
        o,
        "    if (!fn)\n        return vkf_no_fn(&k, VKG_{primary});"
    )
    .ok();
    if let Some(h) = m.cfg.before.get(primary) {
        writeln!(o, "    {h}(&k);").ok();
    }
    let args: Vec<String> = (0..c.params.len()).map(|i| format!("a{i}")).collect();
    let call = format!("fn({})", args.join(", "));
    let ret = m.canon(&c.ret.ty).to_string();
    if let Some(h) = m.cfg.check.get(primary) {
        if ret != "VkResult" || c.ret.ptr > 0 {
            return Err(Error(format!(
                "{}: a check hook needs a command that returns VkResult",
                c.name
            )));
        }
        writeln!(
            o,
            "    VkResult checked = {h}(&k);\n    if (checked < 0) {{\n        c->x[0] = (uint32_t)checked;\n        return vkf_end(&k);\n    }}"
        )
        .ok();
    }
    let has_ret = !(ret == "void" && c.ret.ptr == 0);
    if c.ret.ptr > 0 || matches!(m.kind(&ret), Some(Kind::FuncPtr { .. })) {
        return Err(Error(format!(
            "{}: pointer result; list it in hand_commands",
            c.name
        )));
    }
    if has_ret {
        writeln!(o, "    {ret} r = {call};").ok();
    } else {
        writeln!(o, "    {call};").ok();
    }
    if !gated.is_empty() {
        if ret == "VkResult" {
            writeln!(o, "    if (r >= 0) {{").ok();
            for g in &gated {
                for line in g.lines() {
                    writeln!(o, "    {line}").ok();
                }
            }
            writeln!(o, "    }}").ok();
        } else {
            for g in &gated {
                writeln!(o, "{g}").ok();
            }
        }
    }
    after.clear();
    if let Some(h) = m.cfg.after.get(primary) {
        writeln!(o, "    {h}(&k);").ok();
    }
    if has_ret {
        let l = m.type_layout(&ret)?;
        if l.size == 8 {
            writeln!(o, "    c->x[0] = (uint64_t)r;").ok();
        } else {
            writeln!(o, "    c->x[0] = (uint32_t)r;").ok();
        }
    }
    writeln!(o, "    return vkf_end(&k);\n}}\n").ok();
    Ok(())
}

/// Emits the header, the converters and the thunks.
pub fn emit(m: &mut Model) -> Result<CFiles, Error> {
    let sel = m.sel;
    let reg = m.reg;
    let cmds: Vec<(String, Vec<String>, Audience)> = sel
        .commands
        .iter()
        .map(|(d, (n, a))| (d.clone(), n.clone(), *a))
        .collect();
    for h in &m.cfg.hand_commands {
        if !cmds.iter().any(|(_, n, _)| n[0] == *h) {
            return Err(Error(format!("hand command {h} is not a selected command")));
        }
    }
    let mut h = String::new();
    writeln!(h, "{HEAD}\n#ifndef RELIFT_VKG_H\n#define RELIFT_VKG_H\n").ok();
    writeln!(
        h,
        "#include \"vkg_types.h\"\n#include <relift/arm64/abi.h>\n"
    )
    .ok();
    writeln!(h, "typedef struct vkf_call vkf_call;\n").ok();
    writeln!(h, "enum vkg_cmd {{").ok();
    for (i, (_, n, _)) in cmds.iter().enumerate() {
        writeln!(h, "    VKG_{} = {i},", n[0]).ok();
    }
    writeln!(h, "    VKG_COUNT = {}\n}};\n", cmds.len()).ok();
    for (i, d) in m.dispatchable.iter().enumerate() {
        writeln!(h, "#define VKG_KIND_{d} {}", i + 1).ok();
    }
    writeln!(h, "#define VKG_KIND_COUNT {}\n", m.dispatchable.len() + 1).ok();
    writeln!(h, "/** @brief One command: its primary name, other names, level (0 global, 1 instance, 2 device) and whether the guest sees it. */").ok();
    writeln!(h, "typedef struct vkg_cmd_info {{\n    const char *name;\n    const char *const *aliases;\n    uint8_t level;\n    uint8_t guest;\n}} vkg_cmd_info;\n").ok();
    writeln!(
        h,
        "/** @brief A guest-visible command name and its command. */"
    )
    .ok();
    writeln!(
        h,
        "typedef struct vkg_name {{\n    const char *name;\n    uint16_t cmd;\n}} vkg_name;\n"
    )
    .ok();
    writeln!(h, "extern const vkg_cmd_info vkg_cmds[VKG_COUNT];").ok();
    writeln!(
        h,
        "extern const vkg_name vkg_names[];\nextern const uint32_t vkg_name_count;"
    )
    .ok();
    writeln!(h, "extern const rl_fn vkg_thunks[VKG_COUNT];").ok();
    writeln!(h, "extern const char *const vkg_instance_exts[];\nextern const uint32_t vkg_instance_ext_count;").ok();
    writeln!(
        h,
        "extern const char *const vkg_device_exts[];\nextern const uint32_t vkg_device_ext_count;\n"
    )
    .ok();
    writeln!(h, "void *vkg_chain_in(vkf_call *k, uint64_t g);\nvoid vkg_chain_out(vkf_call *k, uint64_t g, const void *h);").ok();
    let conv: Vec<String> = m
        .converted
        .iter()
        .filter(|t| !dropped(m, t))
        .cloned()
        .collect();
    for t in &conv {
        let p = if is_hand_struct(m, t) { "vkh" } else { "vkg" };
        writeln!(h, "void {p}_in_{t}(vkf_call *k, {t} *h, uint64_t g);").ok();
        writeln!(
            h,
            "void {p}_out_{t}(vkf_call *k, uint64_t g, const {t} *h);"
        )
        .ok();
        writeln!(h, "{t} *vkg_ain_{t}(vkf_call *k, uint64_t g, uint64_t n);").ok();
        writeln!(
            h,
            "void vkg_aout_{t}(vkf_call *k, uint64_t g, const {t} *h, uint64_t n);"
        )
        .ok();
    }
    writeln!(h).ok();
    for c in &m.cfg.hand_commands {
        writeln!(h, "int vkh_{c}(rl_ctx *restrict c, uint8_t *mem);").ok();
    }
    let mut hooks: Vec<&String> = m.cfg.before.values().chain(m.cfg.after.values()).collect();
    hooks.sort();
    hooks.dedup();
    for f in hooks {
        writeln!(h, "void {f}(vkf_call *k);").ok();
    }
    let mut checks: Vec<&String> = m.cfg.check.values().collect();
    checks.sort();
    checks.dedup();
    for f in checks {
        writeln!(h, "VkResult {f}(vkf_call *k);").ok();
    }
    writeln!(h, "\n#endif").ok();

    let mut cv = String::new();
    writeln!(cv, "{HEAD}\n#include \"vkf.h\"\n\n#include <string.h>\n").ok();
    for t in &conv {
        emit_struct(m, t, &mut cv)?;
    }
    writeln!(cv, "void *vkg_chain_in(vkf_call *k, uint64_t g)\n{{\n    while (g) {{\n        switch (vkf_g32(k, g)) {{").ok();
    let mut stypes = Vec::new();
    for t in &sel.types {
        if let Some(Kind::Struct { members, .. }) = reg.types.get(t).map(|x| &x.kind)
            && let Some(v) = members.first().and_then(|f| f.values.clone())
        {
            stypes.push((t.clone(), v));
        }
    }
    for (t, v) in &stypes {
        writeln!(
            cv,
            "        case {v}: {{\n            {t} *h = vkf_alloc(k, sizeof *h);\n            {}(k, h, g);\n            return h;\n        }}",
            in_fn(m, t)
        )
        .ok();
    }
    writeln!(cv, "        default:\n            vkf_unknown_stype(k, vkf_g32(k, g));\n            g = vkf_g64(k, g + 8);\n        }}\n    }}\n    return NULL;\n}}\n").ok();
    writeln!(cv, "void vkg_chain_out(vkf_call *k, uint64_t g, const void *h)\n{{\n    while (g && h) {{\n        switch (vkf_g32(k, g)) {{").ok();
    for (t, v) in &stypes {
        writeln!(
            cv,
            "        case {v}:\n            {}(k, g, (const {t} *)h);\n            return;",
            out_fn(m, t)
        )
        .ok();
    }
    writeln!(
        cv,
        "        default:\n            g = vkf_g64(k, g + 8);\n        }}\n    }}\n}}"
    )
    .ok();

    let mut th = String::new();
    writeln!(th, "{HEAD}\n#include \"vkf.h\"\n").ok();
    for (def, names, aud) in &cmds {
        if *aud == Audience::Guest && !m.cfg.hand_commands.contains(&names[0]) {
            emit_thunk(m, def, &names[0], &mut th)?;
        }
    }
    for (i, (_, names, _)) in cmds.iter().enumerate() {
        if names.len() > 1 {
            let list: Vec<String> = names[1..].iter().map(|n| format!("\"{n}\"")).collect();
            writeln!(
                th,
                "static const char *const vkg_alias_{i}[] = {{{}, NULL}};",
                list.join(", ")
            )
            .ok();
        }
    }
    writeln!(th, "\nconst vkg_cmd_info vkg_cmds[VKG_COUNT] = {{").ok();
    for (i, (def, names, aud)) in cmds.iter().enumerate() {
        let al = if names.len() > 1 {
            format!("vkg_alias_{i}")
        } else {
            "NULL".into()
        };
        let lvl = level(m, &reg.commands[def]);
        writeln!(
            th,
            "    {{\"{}\", {al}, {lvl}, {}}},",
            names[0],
            u8::from(*aud == Audience::Guest)
        )
        .ok();
    }
    writeln!(th, "}};\n").ok();
    let mut all: Vec<(String, usize)> = Vec::new();
    for (i, (_, names, aud)) in cmds.iter().enumerate() {
        if *aud == Audience::Guest {
            for n in names {
                all.push((n.clone(), i));
            }
        }
    }
    all.sort();
    writeln!(th, "const vkg_name vkg_names[] = {{").ok();
    for (n, i) in &all {
        writeln!(th, "    {{\"{n}\", VKG_{}}},", cmds[*i].1[0]).ok();
    }
    writeln!(th, "}};\nconst uint32_t vkg_name_count = {};\n", all.len()).ok();
    writeln!(th, "const rl_fn vkg_thunks[VKG_COUNT] = {{").ok();
    for (_, names, aud) in &cmds {
        let n = &names[0];
        if *aud != Audience::Guest {
            writeln!(th, "    NULL,").ok();
        } else if m.cfg.hand_commands.contains(n) {
            writeln!(th, "    vkh_{n},").ok();
        } else {
            writeln!(th, "    vkt_{n},").ok();
        }
    }
    writeln!(th, "}};\n").ok();
    for (name, list) in [
        ("instance", &sel.guest_instance_exts),
        ("device", &sel.guest_device_exts),
    ] {
        writeln!(th, "const char *const vkg_{name}_exts[] = {{").ok();
        for e in list {
            writeln!(th, "    \"{e}\",").ok();
        }
        writeln!(
            th,
            "    NULL\n}};\nconst uint32_t vkg_{name}_ext_count = {};\n",
            list.len()
        )
        .ok();
    }
    Ok(CFiles {
        header: h,
        convert: cv,
        thunks: th,
    })
}
