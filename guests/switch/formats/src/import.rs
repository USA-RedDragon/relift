//! Import: read a decrypted dump, a `.nup` file or an extracted tree, and
//! write the exefs files, the decompressed modules, the module table, and
//! the game's romfs and each DLC's romfs as one image each
//! ([`crate::romfs_image`]): from a `.nup`, a RomFS map (`romfs.map`) that
//! reads the files in place in the `.nup` (plus `romfs.blob` for its zstd
//! files), so a game with hundreds of thousands of romfs files costs a few
//! files on disk; from a tree, a plain image (`romfs.img`). Every file goes
//! through relift-cache's write-if-changed writers and romfs data streams
//! through them, so a re-import of the same dump touches nothing and no
//! large file is held in memory. A romfs form left by an older import (a
//! `romfs/` tree) is removed.
//!
//! The extracted tree is the layout NUP packers read:
//!
//! ```text
//! <dir>/base/{exefs,romfs}
//! <dir>/updates/<decimal version>/{exefs,romfs}   full patched romfs, not a delta
//! <dir>/dlc/<16-hex add-on title id>/<index>/romfs
//! ```
//!
//! or a bare content directory holding `exefs/` and/or `romfs/`, taken as
//! the base. The newest update is used unless [`Options::update`] says
//! otherwise; its exefs and romfs replace the base's whole when it has them.
//!
//! Encrypted dumps (NSP, NSZ, XCI, XCZ, NCA) are refused with
//! [`Error::Encrypted`]: relift reads decrypted dumps only.
//!
//! A module is identified by the module name in its .rodata header plus its
//! build ID, never by the exefs slot it sits in.

use std::path::{Path, PathBuf};
use std::sync::Arc;

use crate::bytes::sha256;
use crate::error::{Error, Result, malformed};
use crate::npdm::Npdm;
use crate::nso::Nso;
use crate::nup::{Nup, PackageKind, TLV_DISPLAY_VERSION, TLV_ICON, TLV_NACP, UpdateSelect};
use crate::romfs_image;
use crate::storage::{FileStorage, Shared, Storage, read_vec};

/// One imported module.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Module {
    /// The module name from .rodata (`nnSdk`, `vulkan`, the game's name),
    /// or the slot name when the module records none.
    pub name: String,
    /// The exefs slot it came from (`main`, `sdk`, `subsdk0`, ...).
    pub slot: String,
    /// The build ID, lowercase hex.
    pub build_id: String,
    /// SHA-256 of the written uncompressed NSO, lowercase hex.
    pub sha256: String,
    /// The written file, relative to the output directory.
    pub path: String,
}

/// What an import produced.
#[derive(Clone, Debug)]
pub struct Report {
    /// The program ID, from `main.npdm`.
    pub program_id: u64,
    /// The title version: the selected update's, or 0 for the base.
    pub version: u32,
    /// The modules, in exefs order.
    pub modules: Vec<Module>,
    /// The parsed `main.npdm`, if present.
    pub npdm: Option<Npdm>,
    /// How many romfs files there are.
    pub romfs_files: usize,
    /// The DLC directories written, relative to the output directory
    /// (`dlc/<title id>/<index>`).
    pub dlc: Vec<String>,
    /// The romfs directories of the container's other programs, relative
    /// to the output directory (`programs/<base title id>`), which the
    /// imported program may open by program index.
    pub programs: Vec<String>,
    /// How many files (romfs and others) were rewritten.
    pub written: usize,
}

impl Report {
    /// The module table as TOML text.
    pub fn module_table(&self) -> String {
        let mut s = String::from("# Generated by relift import.\n");
        for m in &self.modules {
            s.push_str(&format!(
                "\n[[module]]\nname = {}\nslot = {}\nbuild_id = \"{}\"\nsha256 = \"{}\"\npath = {}\n",
                quote(&m.name),
                quote(&m.slot),
                m.build_id,
                m.sha256,
                quote(&m.path)
            ));
        }
        s
    }
}

/// Quote a string as a TOML basic string.
pub fn quote(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 || c == '\x7f' => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// What an import reports while it works, for progress output. A stage is
/// `exefs`, `romfs` or a `dlc/<title id>/<index>` directory.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Event<'a> {
    /// A stage starts, with its totals when they are known up front.
    Begin {
        /// The stage name.
        stage: &'a str,
        /// Files in the stage.
        files: Option<u64>,
        /// Bytes in the stage.
        bytes: Option<u64>,
    },
    /// This many bytes were written since the last event.
    Chunk(u64),
    /// One file is complete.
    File,
    /// The stage is complete.
    End,
}

/// Options of an import.
#[derive(Clone, Copy, Debug)]
pub struct Options {
    /// Which update to layer over the base: the newest by default.
    pub update: UpdateSelect,
    /// Which program (its base's title id) of a container holding several.
    pub program: Option<u64>,
}

impl Options {
    /// The update for the container's other programs: the newest, or none
    /// when the base alone was asked for (a version names one program's).
    fn update_of_other(&self) -> UpdateSelect {
        match self.update {
            UpdateSelect::None => UpdateSelect::None,
            _ => UpdateSelect::Newest,
        }
    }
}

impl Default for Options {
    fn default() -> Options {
        Options {
            update: UpdateSelect::Newest,
            program: None,
        }
    }
}

/// File extensions of encrypted dumps, refused before the bytes are read.
const ENCRYPTED_EXTENSIONS: &[&str] = &["nsp", "nsz", "xci", "xcz", "nca", "ncz"];

/// Refuse an encrypted dump in `storage` (named `path`): by extension, or
/// by a PFS0 (NSP), game card (XCI) or plaintext NCA header magic.
fn refuse_encrypted(path: &Path, storage: &dyn Storage) -> Result<()> {
    let ext = path
        .extension()
        .map(|e| e.to_string_lossy().to_ascii_lowercase());
    if ext.is_some_and(|e| ENCRYPTED_EXTENSIONS.contains(&e.as_str())) {
        return Err(Error::Encrypted(path.display().to_string()));
    }
    let head = read_vec(storage, 0, 0x400.min(storage.size()))?;
    let at = |o: usize, m: &[u8]| head.get(o..o + m.len()) == Some(m);
    let plain_header = [b"NCA0", b"NCA2", b"NCA3"].iter().any(|m| at(0x200, *m));
    if at(0, b"PFS0") || at(0x100, b"HEAD") || at(0x300, b"HEAD") || plain_header {
        return Err(Error::Encrypted(path.display().to_string()));
    }
    Ok(())
}

fn open(path: &Path) -> Result<Shared> {
    Ok(Arc::new(FileStorage::open(path)?))
}

/// Import the dump at `input` (a `.nup` file or an extracted tree) into
/// `out`: `exefs/<slot>`, `modules/<module name>.nso` (uncompressed),
/// `modules.toml`, the romfs (`romfs.map` or `romfs.img`),
/// `dlc/<title id>/<index>/` holding each DLC's romfs the same way, and for
/// a container holding several programs `programs/<title id>/` holding
/// each other program's romfs.
///
/// # Errors
///
/// An encrypted input ([`Error::Encrypted`]), an unknown file, a layout
/// without an exefs, a hash mismatch, a malformed file or a write error.
pub fn import(input: &Path, out: &Path, opts: &Options) -> Result<Report> {
    import_with(input, out, opts, &mut |_| {})
}

/// As [`import`], telling `on` about each stage and the bytes and files
/// written in it.
///
/// # Errors
///
/// As [`import`].
pub fn import_with(
    input: &Path,
    out: &Path,
    opts: &Options,
    on: &mut dyn FnMut(Event),
) -> Result<Report> {
    let meta = std::fs::metadata(input).map_err(|e| {
        Error::Io(std::io::Error::new(
            e.kind(),
            format!("{}: {e}", input.display()),
        ))
    })?;
    if meta.is_dir() {
        return import_tree(input, out, opts, on);
    }
    let storage = open(input)?;
    let head = read_vec(&*storage, 0, 4.min(storage.size()))?;
    if head.get(..3) == Some(&crate::nup::MAGIC[..3]) {
        return import_nup(&Nup::open(storage)?, input, out, opts, on);
    }
    refuse_encrypted(input, &*storage)?;
    malformed(format!(
        "{}: not a .nup file (unknown magic) and not a dump directory; {}",
        input.display(),
        crate::error::ENCRYPTED_HINT
    ))
}

fn new_report(version: u32) -> Report {
    Report {
        program_id: 0,
        version,
        modules: Vec::new(),
        npdm: None,
        romfs_files: 0,
        dlc: Vec::new(),
        programs: Vec::new(),
        written: 0,
    }
}

/// The program ID from the imported `main.npdm`, or `fallback`.
fn program_id(report: &mut Report, fallback: Option<u64>) -> Result<()> {
    report.program_id = match (&report.npdm, fallback) {
        (Some(n), _) => n.program_id,
        (None, Some(id)) => id,
        (None, None) => {
            return malformed("the exefs has no main.npdm, so the program ID is unknown");
        }
    };
    Ok(())
}

fn nup_romfs(
    nup: &Nup,
    input: &Path,
    files: &[(String, crate::nup::NupEntry)],
    dirs: &[String],
    dir: &Path,
    on: &mut dyn FnMut(Event),
) -> Result<usize> {
    let w = romfs_image::write_nup(nup, input, files, dirs, dir, &mut |e| match e {
        Some(n) => on(Event::Chunk(n)),
        None => on(Event::File),
    })?;
    romfs_image::remove_others(dir, romfs_image::MAP_NAME)?;
    Ok(w.written)
}

fn import_nup(
    nup: &Nup,
    input: &Path,
    out: &Path,
    opts: &Options,
    on: &mut dyn FnMut(Event),
) -> Result<Report> {
    let t = nup.program_title(opts.program, opts.update)?;
    if t.exefs.is_empty() {
        return malformed("NUP: the selected update and the base have no exefs");
    }
    prepare(out)?;
    let mut report = new_report(t.version);
    report.romfs_files = t.romfs.len();
    let packages = nup.packages();
    let control = |ty| {
        [t.update, t.base]
            .into_iter()
            .flatten()
            .find_map(|i| packages.get(i).and_then(|p| p.tlv(ty)))
    };
    for (name, ty) in [(CONTROL_NACP, TLV_NACP), (CONTROL_ICON, TLV_ICON)] {
        if let Some(bytes) = control(ty) {
            control_file(out, name, bytes, &mut report)?;
        }
    }
    if let Some(bytes) = control(TLV_DISPLAY_VERSION) {
        control_file(out, CONTROL_VERSION, bytes, &mut report)?;
    }
    on(Event::Begin {
        stage: "exefs",
        files: Some(t.exefs.len() as u64),
        bytes: Some(t.exefs.iter().map(|(_, e)| e.size).sum()),
    });
    for (name, e) in &t.exefs {
        let bytes = nup.read(e)?;
        exefs_file(out, name, &bytes, &mut report)?;
        on(Event::Chunk(bytes.len() as u64));
        on(Event::File);
    }
    on(Event::End);
    program_id(&mut report, Some(t.program_id))?;
    on(Event::Begin {
        stage: "romfs",
        files: Some(t.romfs.len() as u64),
        bytes: Some(t.romfs.iter().map(|(_, e)| e.size).sum()),
    });
    report.written += nup_romfs(nup, input, &t.romfs, &t.romfs_dirs, out, on)?;
    on(Event::End);
    let mut seen: Vec<u64> = Vec::new();
    for (i, p) in nup.packages().iter().enumerate() {
        if p.record.kind != PackageKind::Addon {
            continue;
        }
        let id = p.record.title_id;
        let index = seen.iter().filter(|s| **s == id).count();
        seen.push(id);
        let Some(addon) = nup.package_title(i) else {
            continue;
        };
        let rel = format!("dlc/{id:016x}/{index}");
        on(Event::Begin {
            stage: &rel,
            files: Some(addon.romfs.len() as u64),
            bytes: Some(addon.romfs.iter().map(|(_, e)| e.size).sum()),
        });
        report.written += nup_romfs(
            nup,
            input,
            &addon.romfs,
            &addon.romfs_dirs,
            &out.join(&rel),
            on,
        )?;
        on(Event::End);
        report.dlc.push(rel);
    }
    for i in nup.bases() {
        if Some(i) == t.base {
            continue;
        }
        let id = nup.packages()[i].record.title_id;
        let other = nup.program_title(Some(id), opts.update_of_other())?;
        let rel = format!("programs/{id:016x}");
        on(Event::Begin {
            stage: &rel,
            files: Some(other.romfs.len() as u64),
            bytes: Some(other.romfs.iter().map(|(_, e)| e.size).sum()),
        });
        report.written += nup_romfs(
            nup,
            input,
            &other.romfs,
            &other.romfs_dirs,
            &out.join(&rel),
            on,
        )?;
        on(Event::End);
        report.programs.push(rel);
    }
    finish(out, &mut report)?;
    Ok(report)
}

/// The control data of a title, as written beside `exefs/`.
const CONTROL_NACP: &str = "control.nacp";
const CONTROL_ICON: &str = "icon.jpg";
/// The display version a package's meta block holds, kept when the package has it apart from a NACP.
const CONTROL_VERSION: &str = "display_version.txt";

/// One `exefs/` plus `romfs/` directory of an extracted tree, with the
/// control data a dump keeps beside them.
struct Layer {
    exefs: Option<PathBuf>,
    romfs: Option<PathBuf>,
    control: Vec<(&'static str, PathBuf)>,
}

impl Layer {
    fn at(dir: &Path) -> Layer {
        let sub = |n: &str| Some(dir.join(n)).filter(|p| p.is_dir());
        Layer {
            exefs: sub("exefs"),
            romfs: sub("romfs"),
            control: [CONTROL_NACP, CONTROL_ICON]
                .into_iter()
                .map(|n| (n, dir.join(n)))
                .filter(|(_, p)| p.is_file())
                .collect(),
        }
    }

    fn is_empty(&self) -> bool {
        self.exefs.is_none() && self.romfs.is_none()
    }
}

/// An extracted tree read into its parts.
struct Tree {
    base: Option<Layer>,
    updates: Vec<(u32, Layer)>,
    dlc: Vec<(u64, String, PathBuf)>,
}

fn sorted_entries(dir: &Path) -> Result<Vec<(String, PathBuf)>> {
    let mut v = Vec::new();
    for e in std::fs::read_dir(dir)? {
        let e = e?;
        let name = e
            .file_name()
            .into_string()
            .map_err(|n| Error::Format(format!("{}: a name is not UTF-8: {n:?}", dir.display())))?;
        v.push((name, e.path()));
    }
    v.sort();
    Ok(v)
}

fn read_tree(root: &Path) -> Result<Tree> {
    let (base_dir, updates_dir) = (root.join("base"), root.join("updates"));
    if !base_dir.is_dir() && !updates_dir.is_dir() {
        let bare = Layer::at(root);
        if bare.is_empty() {
            return malformed(format!(
                "{}: not a dump directory: want base/ and updates/<version>/ holding exefs/ and romfs/, or exefs/ and romfs/ directly",
                root.display()
            ));
        }
        return Ok(Tree {
            base: Some(bare),
            updates: Vec::new(),
            dlc: Vec::new(),
        });
    }
    let base = if base_dir.is_dir() {
        let l = Layer::at(&base_dir);
        if l.is_empty() {
            return malformed(format!("{}: no exefs/ or romfs/", base_dir.display()));
        }
        Some(l)
    } else {
        None
    };
    let mut updates = Vec::new();
    if updates_dir.is_dir() {
        for (name, path) in sorted_entries(&updates_dir)? {
            if !path.is_dir() {
                continue;
            }
            let v: u32 = name.parse().map_err(|_| {
                Error::Format(format!("{}: not a decimal update version", path.display()))
            })?;
            let l = Layer::at(&path);
            if l.is_empty() {
                return malformed(format!("{}: no exefs/ or romfs/", path.display()));
            }
            updates.push((v, l));
        }
    }
    updates.sort_by_key(|(v, _)| *v);
    let mut dlc = Vec::new();
    let dlc_dir = root.join("dlc");
    if dlc_dir.is_dir() {
        for (name, path) in sorted_entries(&dlc_dir)? {
            let id = match u64::from_str_radix(&name, 16) {
                Ok(id) if name.len() == 16 && path.is_dir() => id,
                _ => continue,
            };
            for (index, at) in sorted_entries(&path)? {
                let romfs = at.join("romfs");
                if romfs.is_dir() {
                    dlc.push((id, index, romfs));
                }
            }
        }
    }
    Ok(Tree { base, updates, dlc })
}

fn import_tree(
    root: &Path,
    out: &Path,
    opts: &Options,
    on: &mut dyn FnMut(Event),
) -> Result<Report> {
    if opts.program.is_some() {
        return Err(Error::Format(
            "a program choice is for containers holding several; a folder dump holds one".into(),
        ));
    }
    let tree = read_tree(root)?;
    let versions = || {
        let v: Vec<String> = tree.updates.iter().map(|(v, _)| v.to_string()).collect();
        if v.is_empty() {
            "none".to_string()
        } else {
            v.join(", ")
        }
    };
    let update = match opts.update {
        UpdateSelect::None => None,
        UpdateSelect::Newest => tree.updates.last(),
        UpdateSelect::Version(want) => Some(
            tree.updates
                .iter()
                .find(|(v, _)| *v == want)
                .ok_or_else(|| {
                    Error::Format(format!(
                        "{}: no update {want} (updates: {})",
                        root.display(),
                        versions()
                    ))
                })?,
        ),
    };
    if update.is_none() && tree.base.is_none() {
        return malformed(format!(
            "{}: no base/ and no update selected (updates: {})",
            root.display(),
            versions()
        ));
    }
    let pick = |f: fn(&Layer) -> Option<&PathBuf>| {
        update
            .and_then(|(_, l)| f(l))
            .or_else(|| tree.base.as_ref().and_then(f))
    };
    let Some(exefs) = pick(|l| l.exefs.as_ref()) else {
        return malformed(format!(
            "{}: no exefs/: neither {} nor the base has one",
            root.display(),
            update.map_or("the selected update".to_string(), |(v, _)| format!(
                "updates/{v}"
            ))
        ));
    };
    let romfs = pick(|l| l.romfs.as_ref());
    prepare(out)?;
    let mut report = new_report(update.map_or(0, |(v, _)| *v));
    for name in [CONTROL_NACP, CONTROL_ICON] {
        let found = update
            .and_then(|(_, l)| l.control.iter().find(|(n, _)| *n == name))
            .or_else(|| {
                tree.base
                    .as_ref()
                    .and_then(|l| l.control.iter().find(|(n, _)| *n == name))
            });
        if let Some((_, path)) = found {
            control_file(out, name, &std::fs::read(path)?, &mut report)?;
        }
    }
    let exefs_files: Vec<(String, PathBuf)> = sorted_entries(exefs)?
        .into_iter()
        .filter(|(name, path)| path.is_file() && !name.starts_with('.'))
        .collect();
    let mut exefs_bytes = 0;
    for (_, path) in &exefs_files {
        exefs_bytes += std::fs::metadata(path)?.len();
    }
    on(Event::Begin {
        stage: "exefs",
        files: Some(exefs_files.len() as u64),
        bytes: Some(exefs_bytes),
    });
    for (name, path) in exefs_files {
        let bytes = std::fs::read(&path)?;
        exefs_file(out, &name, &bytes, &mut report)?;
        on(Event::Chunk(bytes.len() as u64));
        on(Event::File);
    }
    on(Event::End);
    program_id(&mut report, None)?;
    if let Some(r) = romfs {
        let (files, written) = tree_image(r, out, "romfs", on)?;
        report.romfs_files = files;
        report.written += written;
    }
    for (id, index, romfs) in &tree.dlc {
        let rel = format!("dlc/{id:016x}/{index}");
        report.written += tree_image(romfs, &out.join(&rel), &rel, on)?.1;
        report.dlc.push(rel);
    }
    finish(out, &mut report)?;
    Ok(report)
}

/// Write the extracted tree `src` as one plain image `romfs.img` in `dir`,
/// as stage `stage`. Returns (files, files rewritten).
fn tree_image(
    src: &Path,
    dir: &Path,
    stage: &str,
    on: &mut dyn FnMut(Event),
) -> Result<(usize, usize)> {
    let img = romfs_image::Image::from_tree(src)?;
    let files = img.file_count();
    on(Event::Begin {
        stage,
        files: Some(files as u64),
        bytes: Some(img.size()),
    });
    std::fs::create_dir_all(dir)?;
    let mut w = relift_cache::StreamWriter::new(&dir.join(romfs_image::IMAGE_NAME))?;
    img.write_to(&mut w, &mut |e| match e {
        Some(n) => on(Event::Chunk(n)),
        None => on(Event::File),
    })?;
    let written = usize::from(w.finish()?);
    romfs_image::remove_others(dir, romfs_image::IMAGE_NAME)?;
    on(Event::End);
    Ok((files, written))
}

/// Write one exefs file (and, for an NSO, its module) into `out`.
fn exefs_file(out: &Path, name: &str, bytes: &[u8], report: &mut Report) -> Result<()> {
    if name.is_empty() || name.contains(['/', '\\']) || name.starts_with('.') {
        return malformed(format!("exefs: unsafe file name {name:?}"));
    }
    if relift_cache::write_if_changed(&out.join("exefs").join(name), bytes)? {
        report.written += 1;
    }
    if name == "main.npdm" {
        report.npdm = Some(Npdm::parse(bytes)?);
        return Ok(());
    }
    if bytes.get(..4) != Some(b"NSO0") {
        return Ok(());
    }
    let nso = Nso::parse(bytes).map_err(|e| Error::Format(format!("exefs {name}: {e}")))?;
    let flat = nso.to_uncompressed();
    let module_name = nso.module_name().unwrap_or_else(|| name.to_string());
    let safe: String = module_name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || "-_.".contains(c) {
                c
            } else {
                '_'
            }
        })
        .collect();
    if report.modules.iter().any(|m| m.name == module_name) {
        return malformed(format!("two exefs modules are named {module_name:?}"));
    }
    let rel = format!("modules/{safe}.nso");
    if relift_cache::write_if_changed(&out.join(&rel), &flat)? {
        report.written += 1;
    }
    report.modules.push(Module {
        name: module_name,
        slot: name.to_string(),
        build_id: nso.build_id_hex(),
        sha256: crate::hex(&sha256(&flat)),
        path: rel,
    });
    Ok(())
}

fn control_file(out: &Path, name: &str, bytes: &[u8], report: &mut Report) -> Result<()> {
    if relift_cache::write_if_changed(&out.join(name), bytes)? {
        report.written += 1;
    }
    Ok(())
}

fn prepare(out: &Path) -> Result<()> {
    for d in ["exefs", "modules"] {
        std::fs::create_dir_all(out.join(d))?;
    }
    Ok(())
}

fn finish(out: &Path, report: &mut Report) -> Result<()> {
    if relift_cache::write_if_changed(&out.join("modules.toml"), report.module_table().as_bytes())?
    {
        report.written += 1;
    }
    Ok(())
}
