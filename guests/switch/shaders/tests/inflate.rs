const FOX: &[u8] = b"the quick brown fox jumps over the lazy dog; ";

fn words() -> Vec<u8> {
    let mut v = Vec::new();
    for i in 0..400usize {
        let c = 65 + ((i * 7 + i / 3) % 23) as u8;
        v.extend(std::iter::repeat_n(c, 1 + i % 5));
        v.push(b' ');
    }
    v
}

#[test]
fn stored_block() {
    let (out, used) = zlib(STORED, 1 << 20).expect("a stored block decodes");
    assert_eq!(out, FOX);
    assert_eq!(used, STORED.len());
}

#[test]
fn fixed_huffman_with_matches() {
    let (out, used) = zlib(FIXED, 1 << 20).expect("fixed codes decode");
    assert_eq!(out, FOX.repeat(3));
    assert_eq!(used, FIXED.len());
}

#[test]
fn dynamic_huffman() {
    let (out, used) = zlib(DYNAMIC, 1 << 20).expect("dynamic codes decode");
    assert_eq!(out, words());
    assert_eq!(used, DYNAMIC.len());
}

#[test]
fn trailing_bytes_are_left_alone() {
    let mut v = FIXED.to_vec();
    v.extend_from_slice(&[1, 2, 3]);
    assert_eq!(zlib(&v, 1 << 20).expect("decodes").1, FIXED.len());
}

#[test]
fn raw_deflate_without_the_wrapper() {
    let (out, used) = inflate(&FIXED[2..FIXED.len() - 4], 1 << 20).expect("raw deflate decodes");
    assert_eq!(out, FOX.repeat(3));
    assert_eq!(used, FIXED.len() - 6);
}

#[test]
fn bad_input_is_an_error() {
    let mut bad = FIXED.to_vec();
    let last = bad.len() - 1;
    bad[last] ^= 1;
    assert!(zlib(&bad, 1 << 20).is_err(), "a wrong Adler-32");
    assert!(zlib(&FIXED[..10], 1 << 20).is_err(), "a cut stream");
    assert!(zlib(DYNAMIC, 100).is_err(), "output over the limit");
    assert!(zlib(&[0x79, 0x01, 0, 0], 100).is_err(), "a bad header");
    assert!(inflate(&[0x07], 100).is_err(), "a reserved block type");
}
