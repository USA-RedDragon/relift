//! `vkg_types.h`: the Vulkan types of the selection, written from the
//! registry so the runtime needs no host Vulkan headers, plus static asserts
//! that pin every struct to its LP64 layout on a 64-bit compiler: the host
//! layout, which is also the AArch64 guest's.

use std::collections::BTreeSet;
use std::fmt::Write;

use crate::Error;
use crate::model::Model;
use crate::registry::{Decl, Kind, Value};

fn value_text(v: &Value, wide: bool) -> String {
    match v {
        Value::Literal(l) => l.clone(),
        Value::BitPos(b) if wide => format!("0x{:016X}ULL", 1u64 << b),
        Value::BitPos(b) => format!("0x{:08X}", 1u64 << b),
        Value::Alias(a) => a.clone(),
    }
}

/// The C type of a declaration without its name (arrays become pointers in parameters only).
pub fn type_text(d: &Decl) -> String {
    let t = d.text.trim();
    let cut = t.rfind(d.name.as_str()).unwrap_or(t.len());
    t[..cut]
        .trim()
        .replace(" *", "*")
        .replace('*', " *")
        .trim()
        .to_string()
}

fn params_text(params: &[Decl]) -> String {
    if params.is_empty() {
        return "void".into();
    }
    params
        .iter()
        .map(|p| p.text.clone())
        .collect::<Vec<_>>()
        .join(", ")
}

/// Emits the types header.
pub fn emit(m: &mut Model, tag: &str) -> Result<String, Error> {
    let reg = m.reg;
    let sel = m.sel;
    let mut o = String::new();
    let w = &mut o;
    writeln!(w, "/* Generated by relift-vkgen from vk.xml {tag} (Apache-2.0 OR MIT, The Khronos Group Inc.). Do not edit. */").ok();
    writeln!(
        w,
        "#ifndef RELIFT_VKG_TYPES_H\n#define RELIFT_VKG_TYPES_H\n"
    )
    .ok();
    writeln!(w, "#include <stddef.h>\n#include <stdint.h>\n").ok();
    writeln!(w, "#define VKAPI_PTR\n").ok();
    for c in &reg.constants {
        if let Some(d) = reg.enum_values.get(c) {
            writeln!(w, "#define {} {}", c, value_text(&d.value, false)).ok();
        }
    }
    for e in &sel.enums {
        if reg.constants.contains(e) {
            continue;
        }
        if let Some(d) = reg.enum_values.get(e)
            && d.group.is_none()
        {
            writeln!(w, "#define {} {}", e, value_text(&d.value, false)).ok();
        }
    }
    writeln!(w).ok();
    let types: Vec<&String> = sel.types.iter().collect();
    let kind = |t: &str| reg.types.get(t).map(|x| &x.kind);
    let mut base: Vec<(&String, &String)> = Vec::new();
    for t in &types {
        if let Some(Kind::Base(Some(b))) = kind(t) {
            base.push((t, b));
        }
    }
    base.sort_by_key(|(t, b)| (reg.types.contains_key(*b), (*t).clone()));
    for (t, b) in base {
        writeln!(w, "typedef {b} {t};").ok();
    }
    for t in &types {
        if let Some(Kind::Base(None)) = kind(t) {
            writeln!(w, "typedef struct {t} {t};").ok();
        }
    }
    writeln!(
        w,
        "#if UINTPTR_MAX > 0xFFFFFFFFu\n#define VKG_NON_DISPATCHABLE(t) typedef struct t##_T *t\n#else\n#define VKG_NON_DISPATCHABLE(t) typedef uint64_t t\n#endif"
    )
    .ok();
    for t in &types {
        match kind(t) {
            Some(Kind::Handle { dispatchable: true }) => {
                writeln!(w, "typedef struct {t}_T *{t};").ok();
            }
            Some(Kind::Handle {
                dispatchable: false,
            }) => {
                writeln!(w, "VKG_NON_DISPATCHABLE({t});").ok();
            }
            _ => {}
        }
    }
    writeln!(w).ok();
    for t in &types {
        if !matches!(kind(t), Some(Kind::Enum)) {
            continue;
        }
        let wide = reg.enum_width.get(*t) == Some(&64);
        let mut vals: Vec<(&String, &Value)> = reg
            .enum_values
            .values()
            .filter(|d| d.base || sel.enums.contains(&d.name))
            .filter(|d| d.group.as_deref() == Some(t.as_str()))
            .map(|d| (&d.name, &d.value))
            .collect();
        vals.sort_by_key(|(n, v)| (matches!(v, Value::Alias(_)), (*n).clone()));
        let mut placed: BTreeSet<&String> = BTreeSet::new();
        let mut ordered = Vec::new();
        let mut rest = vals;
        while !rest.is_empty() {
            let before = rest.len();
            let mut keep = Vec::new();
            for (n, v) in rest {
                let ready = match v {
                    Value::Alias(a) => placed.iter().any(|p| *p == a),
                    _ => true,
                };
                if ready {
                    placed.insert(n);
                    ordered.push((n, v));
                } else {
                    keep.push((n, v));
                }
            }
            if keep.len() == before {
                return Err(Error(format!(
                    "enum {t}: alias of a value outside the selection"
                )));
            }
            rest = keep;
        }
        let vals = ordered;
        if wide {
            writeln!(w, "typedef VkFlags64 {t};").ok();
            for (n, v) in vals {
                writeln!(w, "#define {n} (({t})({}))", value_text(v, true)).ok();
            }
        } else {
            writeln!(w, "typedef enum {t} {{").ok();
            for (n, v) in vals {
                writeln!(w, "    {n} = {},", value_text(v, false)).ok();
            }
            let max = format!(
                "{}_MAX_ENUM",
                t.chars().fold(String::new(), |mut s, c| {
                    if c.is_ascii_uppercase() && !s.is_empty() {
                        s.push('_');
                    }
                    s.push(c.to_ascii_uppercase());
                    s
                })
            );
            writeln!(w, "    {max} = 0x7FFFFFFF\n}} {t};").ok();
        }
    }
    writeln!(w).ok();
    for t in &types {
        if let Some(Kind::Bitmask { over, .. }) = kind(t) {
            writeln!(w, "typedef {over} {t};").ok();
        }
    }
    for t in &types {
        if let Some(Kind::Struct { union, .. }) = kind(t) {
            let k = if *union { "union" } else { "struct" };
            writeln!(w, "typedef {k} {t} {t};").ok();
        }
    }
    writeln!(w).ok();
    for t in &types {
        if let Some(Kind::FuncPtr { ret, params }) = kind(t) {
            writeln!(
                w,
                "typedef {} (VKAPI_PTR *{t})({});",
                type_text(ret),
                params_text(params)
            )
            .ok();
        }
    }
    for t in &types {
        if let Some(Kind::Alias(a)) = kind(t) {
            writeln!(w, "typedef {a} {t};").ok();
        }
    }
    writeln!(w).ok();
    let mut done = BTreeSet::new();
    let structs: Vec<String> = types
        .iter()
        .filter(|t| matches!(kind(t), Some(Kind::Struct { .. })))
        .map(|t| (*t).clone())
        .collect();
    fn visit(m: &Model, t: &str, done: &mut BTreeSet<String>, w: &mut String) {
        if !done.insert(t.to_string()) {
            return;
        }
        let Some(Kind::Struct { members, union, .. }) = m.reg.types.get(t).map(|x| &x.kind) else {
            return;
        };
        for mem in members {
            let mt = m.reg.resolve(&mem.ty);
            if mem.ptr == 0 && m.is_struct(mt) {
                visit(m, mt, done, w);
            }
        }
        let k = if *union { "union" } else { "struct" };
        writeln!(w, "{k} {t} {{").ok();
        for mem in members {
            writeln!(w, "    {};", mem.text).ok();
        }
        writeln!(w, "}};\n").ok();
    }
    for t in &structs {
        visit(m, t, &mut done, w);
    }
    writeln!(w, "#if UINTPTR_MAX > 0xFFFFFFFFu").ok();
    for t in &structs {
        let l = m.host_layout(t)?;
        writeln!(
            w,
            "_Static_assert(sizeof({t}) == {} && _Alignof({t}) == {}, \"{t} guest layout\");",
            l.layout.size, l.layout.align
        )
        .ok();
        for (mem, off) in m.members(t).iter().zip(&l.offsets) {
            writeln!(
                w,
                "_Static_assert(offsetof({t}, {}) == {off}, \"{t}.{} guest offset\");",
                mem.name, mem.name
            )
            .ok();
        }
    }
    writeln!(w, "#endif").ok();
    writeln!(w).ok();
    for (def, (names, _)) in &sel.commands {
        let c = &reg.commands[def];
        for n in names {
            writeln!(
                w,
                "typedef {} (VKAPI_PTR *PFN_{n})({});",
                type_text(&c.ret),
                params_text(&c.params)
            )
            .ok();
        }
    }
    writeln!(w, "\n#endif").ok();
    Ok(o)
}
