//! `vki.c` and `vki_layout.c`: the Vulkan forwarding of an i386 guest.
//!
//! The thunks run on the i386 core of the runtime (`tg.h`): they read
//! their cdecl arguments from 4-byte stack slots, give results in eax and
//! edx, and pass dispatchable handles as 4-byte tokens. The guest layout of
//! every struct differs from the host's wherever a pointer, a `size_t`, a
//! dispatchable handle or an 8-byte scalar is involved, so those structs are
//! converted member by member; the rest (and arrays of them) pass in place.
//! `vki_layout.c` holds the guest layouts as static asserts for a compiler
//! targeting i386.

use std::fmt::Write;

use crate::Error;
use crate::emit_c::len_expr;
use crate::emit_types::type_text;
use crate::model::Model;
use crate::registry::{Command, Decl, Kind};
use crate::select::Audience;

const HEAD: &str = "/* Generated by relift-vkgen from vk.xml for an i386 guest. Do not edit. */";

/// The soname the guest links.
const SONAME: &str = "libvulkan.so.1";

/// The two generated files.
pub struct I386Files {
    /// `vki.c`: converters, thunks and the library table.
    pub thunks: String,
    /// `vki_layout.c`: guest layouts as static asserts.
    pub layout: String,
}

const PRELUDE: &str = r#"#include "../../../i386/tg.h"
#include "vkg_types.h"

#include <pthread.h>
#include <stdio.h>

/** @brief A dispatchable handle in a struct: 0 is NULL. */
static inline void *vki_unhandle_field(uint32_t t)
{
    return t ? tg_unhandle(t, "struct member") : NULL;
}

/** @brief A host size_t as a guest one; a size the guest cannot hold stops the program. */
static inline uint32_t vki_size32(size_t n)
{
    if (n > 0xFFFFFFFFu)
        tg_fail("vulkan", "a size beyond 4 GiB for an i386 guest");
    return (uint32_t)n;
}

/** @brief n dispatchable handle tokens at guest address g as host handles. */
static void **vki_unwrap_n(tg_call *k, uint32_t g, uint64_t n)
{
    if (!g)
        return NULL;
    void **h = tg_alloc(k, (n ? n : 1) * sizeof *h);
    for (uint64_t i = 0; i < n; i++)
        h[i] = vki_unhandle_field((uint32_t)tg_ld(k->mem + g + 4 * i, 4));
    return h;
}

/** @brief n guest string pointers at guest address g as host string pointers. */
static const char *const *vki_strv(tg_call *k, uint32_t g, uint64_t n)
{
    if (!g)
        return NULL;
    const char **h = tg_alloc(k, (n ? n : 1) * sizeof *h);
    for (uint64_t i = 0; i < n; i++)
        h[i] = tg_ptr(k, (uint32_t)tg_ld(k->mem + g + 4 * i, 4));
    return h;
}

static void *vki_chain_in(tg_call *k, uint32_t g);
static void vki_chain_out(tg_call *k, uint32_t g, const void *h);
"#;

fn ld(at: &str) -> String {
    format!("(uint32_t)tg_ld(k->mem + {at}, 4)")
}

fn hand(m: &Model, t: &str) -> bool {
    m.cfg.hand_structs.iter().any(|h| h == t)
}

fn dropped(m: &Model, t: &str) -> bool {
    m.cfg.drop_types.iter().any(|h| h == m.canon(t))
}

fn in_fn(m: &Model, t: &str) -> String {
    if hand(m, t) {
        format!("vkih_in_{t}")
    } else {
        format!("vki_in_{t}")
    }
}

fn out_fn(m: &Model, t: &str) -> String {
    if hand(m, t) {
        format!("vkih_out_{t}")
    } else {
        format!("vki_out_{t}")
    }
}

fn is_funcptr(m: &Model, t: &str) -> bool {
    matches!(m.kind(t), Some(Kind::FuncPtr { .. }))
}

/// Emits `vki_in_T`, `vki_out_T` and the array forms of one converted struct.
fn emit_struct(m: &mut Model, t: &str, o: &mut String) -> Result<(), Error> {
    let l = m.struct_layout(t)?;
    let gsize = l.layout.size;
    let members = m.members(t);
    if matches!(m.kind(t), Some(Kind::Struct { union: true, .. })) {
        return Err(Error(format!(
            "union {t} needs conversion for an i386 guest; list it in hand_structs"
        )));
    }
    if !hand(m, t) {
        writeln!(
            o,
            "static inline void vki_in_{t}(tg_call *k, {t} *h, uint32_t g)\n{{"
        )
        .ok();
        writeln!(o, "    memset(h, 0, sizeof *h);").ok();
        let mut later = String::new();
        for (d, off) in members.iter().zip(&l.offsets) {
            let mt = m.canon(&d.ty).to_string();
            let n = &d.name;
            let elems = m.elems(d)?;
            let at = format!("g + {off}");
            if d.ptr == 0 {
                if m.kind_of(&mt) != 0 {
                    if elems == 1 {
                        writeln!(o, "    h->{n} = ({mt})vki_unhandle_field({});", ld(&at)).ok();
                    } else {
                        writeln!(
                            o,
                            "    for (uint32_t i = 0; i < {elems}; i++)\n        h->{n}[i] = ({mt})vki_unhandle_field({});",
                            ld(&format!("{at} + 4 * i"))
                        )
                        .ok();
                    }
                } else if mt == "size_t" {
                    if elems != 1 {
                        return Err(Error(format!("{t}.{n}: size_t array")));
                    }
                    writeln!(o, "    h->{n} = {};", ld(&at)).ok();
                } else if is_funcptr(m, &mt) {
                    return Err(Error(format!(
                        "{t}.{n} is a function pointer: list {t} in hand_structs"
                    )));
                } else if m.is_struct(&mt) && !m.plain(&mt) {
                    let es = m.struct_layout(&mt)?.layout.size;
                    if d.array.len() > 1 {
                        return Err(Error(format!("{t}.{n}: multi-dimensional struct array")));
                    }
                    if elems == 1 {
                        writeln!(o, "    {}(k, &h->{n}, {at});", in_fn(m, &mt)).ok();
                    } else {
                        writeln!(
                            o,
                            "    for (uint32_t i = 0; i < {elems}; i++)\n        {}(k, &h->{n}[i], {at} + {es} * i);",
                            in_fn(m, &mt)
                        )
                        .ok();
                    }
                } else {
                    writeln!(o, "    memcpy(&h->{n}, k->mem + {at}, sizeof h->{n});").ok();
                }
                continue;
            }
            let gp = ld(&at);
            let field = |x: &str| {
                members
                    .iter()
                    .find(|q| q.name == x)
                    .map(|_| format!("h->{x}"))
            };
            let tt = type_text(d);
            if n == "pNext" {
                writeln!(later, "    h->pNext = vki_chain_in(k, {gp});").ok();
            } else if d.ptr == 1 && dropped(m, &mt) {
                writeln!(later, "    h->{n} = NULL;").ok();
            } else if d.ptr == 1 && (mt == "void" || m.plain(&mt)) {
                writeln!(later, "    h->{n} = ({tt})tg_ptr(k, {gp});").ok();
            } else if d.ptr == 1 && m.kind_of(&mt) != 0 {
                let cnt = len_expr(d.len.as_deref(), &field)?.unwrap_or_else(|| "1".into());
                writeln!(later, "    h->{n} = ({tt})vki_unwrap_n(k, {gp}, {cnt});").ok();
            } else if d.ptr == 1 && m.is_struct(&mt) {
                let cnt = len_expr(d.len.as_deref(), &field)?.unwrap_or_else(|| "1".into());
                writeln!(later, "    h->{n} = vki_ain_{mt}(k, {gp}, {cnt});").ok();
            } else if d.ptr == 2 && mt == "char" && d.pointee_const {
                let cnt = len_expr(d.len.as_deref(), &field)?
                    .ok_or_else(|| Error(format!("{t}.{n}: string array without a count")))?;
                writeln!(later, "    h->{n} = vki_strv(k, {gp}, {cnt});").ok();
            } else {
                return Err(Error(format!(
                    "{t}.{n} ({}) has no i386 conversion; list {t} in hand_structs",
                    d.text
                )));
            }
        }
        o.push_str(&later);
        writeln!(o, "}}\n").ok();
        writeln!(
            o,
            "static inline void vki_out_{t}(tg_call *k, uint32_t g, const {t} *h)\n{{"
        )
        .ok();
        let mut any = false;
        for (d, off) in members.iter().zip(&l.offsets) {
            let mt = m.canon(&d.ty).to_string();
            let n = &d.name;
            let elems = m.elems(d)?;
            let at = format!("g + {off}");
            if d.ptr > 0 {
                if n == "pNext" {
                    writeln!(o, "    vki_chain_out(k, {}, h->pNext);", ld(&at)).ok();
                    any = true;
                }
                continue;
            }
            if n == "sType" || is_funcptr(m, &mt) {
                continue;
            }
            any = true;
            if m.kind_of(&mt) != 0 {
                if elems == 1 {
                    writeln!(o, "    tg_st(k->mem + {at}, 4, tg_handle(h->{n}));").ok();
                } else {
                    writeln!(
                        o,
                        "    for (uint32_t i = 0; i < {elems}; i++)\n        tg_st(k->mem + {at} + 4 * i, 4, tg_handle(h->{n}[i]));"
                    )
                    .ok();
                }
            } else if mt == "size_t" {
                writeln!(o, "    tg_st(k->mem + {at}, 4, vki_size32(h->{n}));").ok();
            } else if m.is_struct(&mt) && !m.plain(&mt) {
                let es = m.struct_layout(&mt)?.layout.size;
                if elems == 1 {
                    writeln!(o, "    {}(k, {at}, &h->{n});", out_fn(m, &mt)).ok();
                } else {
                    writeln!(
                        o,
                        "    for (uint32_t i = 0; i < {elems}; i++)\n        {}(k, {at} + {es} * i, &h->{n}[i]);",
                        out_fn(m, &mt)
                    )
                    .ok();
                }
            } else {
                writeln!(o, "    memcpy(k->mem + {at}, &h->{n}, sizeof h->{n});").ok();
            }
        }
        if !any {
            writeln!(o, "    (void)k;\n    (void)g;\n    (void)h;").ok();
        }
        writeln!(o, "}}\n").ok();
    }
    writeln!(
        o,
        "static inline {t} *vki_ain_{t}(tg_call *k, uint32_t g, uint64_t n)\n{{\n    if (!g)\n        return NULL;\n    {t} *h = tg_alloc(k, (n ? n : 1) * sizeof *h);\n    for (uint64_t i = 0; i < n; i++)\n        {}(k, &h[i], (uint32_t)(g + {gsize} * i));\n    return h;\n}}\n",
        in_fn(m, t)
    )
    .ok();
    writeln!(
        o,
        "static inline void vki_aout_{t}(tg_call *k, uint32_t g, const {t} *h, uint64_t n)\n{{\n    if (!g || !h)\n        return;\n    for (uint64_t i = 0; i < n; i++)\n        {}(k, (uint32_t)(g + {gsize} * i), &h[i]);\n}}\n",
        out_fn(m, t)
    )
    .ok();
    Ok(())
}

/// The stack slot size of a parameter passed by value.
fn slot(m: &mut Model, p: &Decl) -> Result<u32, Error> {
    if p.ptr > 0 || !p.array.is_empty() {
        return Ok(4);
    }
    let t = m.canon(&p.ty).to_string();
    if m.is_struct(&t) || t == "double" {
        return Err(Error(format!("{} by value is not supported", p.text)));
    }
    Ok(if m.type_layout(&t)?.size == 8 { 8 } else { 4 })
}

/// Emits one generated thunk.
fn emit_thunk(
    m: &mut Model,
    def: &str,
    primary: &str,
    idx: usize,
    o: &mut String,
) -> Result<(), Error> {
    let c: Command = m.reg.commands[def].clone();
    writeln!(
        o,
        "static uint64_t vki_{primary}(rl_ctx *c, uint8_t *mem)\n{{\n    tg_call kk, *k = &kk;\n    tg_begin(k, c, mem);"
    )
    .ok();
    let names: Vec<String> = c.params.iter().map(|p| p.name.clone()).collect();
    let mut gated: Vec<String> = Vec::new();
    let mut off = 0u32;
    for (i, p) in c.params.iter().enumerate() {
        let t = m.canon(&p.ty).to_string();
        let at = off;
        off += slot(m, p)?;
        let tt = type_text(p);
        let field = |x: &str| -> Option<String> {
            let j = names.iter().position(|n| n == x)?;
            Some(if c.params[j].ptr == 1 {
                format!("(a{j} ? *a{j} : 0)")
            } else {
                format!("a{j}")
            })
        };
        let field_base = |x: &str| -> Option<String> {
            let j = names.iter().position(|n| n == x)?;
            Some(format!("a{j}"))
        };
        let len = |d: &Decl| -> Result<Option<String>, Error> {
            let Some(l) = d.len.as_deref() else {
                return Ok(None);
            };
            let first = l.split(',').next().unwrap_or("");
            if let Some((p, _)) = first.split_once("->") {
                return len_expr(Some(l), &|x| if x == p { field_base(x) } else { None });
            }
            len_expr(Some(l), &field)
        };
        if p.ptr == 0 && p.array.is_empty() {
            let size = m.type_layout(&t)?.size;
            if m.kind_of(&t) != 0 {
                writeln!(
                    o,
                    "    {t} a{i} = ({t})tg_unhandle(tg_arg32(k, {at}), \"{primary}\");"
                )
                .ok();
            } else if matches!(m.kind(&t), Some(Kind::Handle { .. })) {
                writeln!(o, "    {tt} a{i} = ({tt})(uintptr_t)tg_arg64(k, {at});").ok();
            } else if t == "float" {
                writeln!(
                    o,
                    "    float a{i};\n    {{\n        uint32_t b = tg_arg32(k, {at});\n        memcpy(&a{i}, &b, 4);\n    }}"
                )
                .ok();
            } else if size == 8 {
                writeln!(o, "    {tt} a{i} = ({tt})tg_arg64(k, {at});").ok();
            } else if t == "int32_t" {
                writeln!(o, "    int32_t a{i} = (int32_t)tg_arg32(k, {at});").ok();
            } else if size == 4 {
                writeln!(o, "    {tt} a{i} = ({tt})tg_arg32(k, {at});").ok();
            } else {
                return Err(Error(format!(
                    "{}: parameter {} has an unsupported size",
                    c.name, p.text
                )));
            }
            continue;
        }
        let ptr_tt = if p.array.is_empty() {
            tt.clone()
        } else {
            format!("{tt} *")
        };
        writeln!(o, "    uint32_t g{i} = tg_arg32(k, {at});").ok();
        let ptr = p.ptr.max(1);
        if ptr == 1 && dropped(m, &t) {
            writeln!(o, "    {ptr_tt} a{i} = NULL;\n    (void)g{i};").ok();
        } else if ptr == 1 && t == "size_t" {
            if p.len.is_some() {
                return Err(Error(format!("{}: size_t array {}", c.name, p.text)));
            }
            writeln!(
                o,
                "    size_t s{i} = g{i} ? (size_t)tg_ld(mem + g{i}, 4) : 0;\n    size_t *a{i} = g{i} ? &s{i} : NULL;"
            )
            .ok();
            if !p.pointee_const {
                gated.push(format!(
                    "    if (g{i})\n        tg_st(mem + g{i}, 4, vki_size32(s{i}));"
                ));
            }
        } else if ptr == 1 && (t == "void" || m.plain(&t)) {
            writeln!(o, "    {ptr_tt} a{i} = ({ptr_tt})tg_ptr(k, g{i});").ok();
        } else if ptr == 1 && m.kind_of(&t) != 0 {
            let n = len(p)?.unwrap_or_else(|| "1".into());
            if p.pointee_const {
                writeln!(
                    o,
                    "    {ptr_tt} a{i} = ({ptr_tt})vki_unwrap_n(k, g{i}, {n});"
                )
                .ok();
            } else {
                writeln!(o, "    uint64_t n{i} = {n};").ok();
                writeln!(
                    o,
                    "    {t} *a{i} = g{i} ? tg_alloc(k, (n{i} ? n{i} : 1) * sizeof *a{i}) : NULL;"
                )
                .ok();
                gated.push(format!(
                    "    if (a{i}) {{\n        uint64_t w{i} = {n};\n        for (uint64_t j = 0; j < w{i} && j < n{i}; j++)\n            tg_st(mem + g{i} + 4 * j, 4, tg_handle(a{i}[j]));\n    }}"
                ));
            }
        } else if ptr == 1 && m.is_struct(&t) {
            let n = len(p)?.unwrap_or_else(|| "1".into());
            if p.pointee_const {
                writeln!(o, "    {ptr_tt} a{i} = vki_ain_{t}(k, g{i}, {n});").ok();
            } else {
                writeln!(o, "    uint64_t n{i} = {n};").ok();
                writeln!(o, "    {t} *a{i} = vki_ain_{t}(k, g{i}, n{i});").ok();
                gated.push(format!(
                    "    {{\n        uint64_t w{i} = {n};\n        vki_aout_{t}(k, g{i}, a{i}, w{i} < n{i} ? w{i} : n{i});\n    }}"
                ));
            }
        } else if ptr == 2 && t == "char" && p.pointee_const {
            let n = len(p)?
                .ok_or_else(|| Error(format!("{}: string array without a count", c.name)))?;
            writeln!(o, "    {ptr_tt} a{i} = vki_strv(k, g{i}, {n});").ok();
        } else {
            return Err(Error(format!(
                "{}: parameter {} has no i386 conversion; list the command in hand_commands",
                c.name, p.text
            )));
        }
    }
    writeln!(
        o,
        "    PFN_{primary} fn = (PFN_{primary})vki_host({idx}, \"{primary}\");"
    )
    .ok();
    let args: Vec<String> = (0..c.params.len()).map(|i| format!("a{i}")).collect();
    let call = format!("fn({})", args.join(", "));
    let ret = m.canon(&c.ret.ty).to_string();
    let has_ret = !(ret == "void" && c.ret.ptr == 0);
    if c.ret.ptr > 0 || is_funcptr(m, &ret) {
        return Err(Error(format!(
            "{}: pointer result; list it in hand_commands",
            c.name
        )));
    }
    if has_ret {
        writeln!(o, "    {ret} r = {call};").ok();
    } else {
        writeln!(o, "    {call};").ok();
    }
    if !gated.is_empty() {
        if ret == "VkResult" {
            writeln!(o, "    if (r >= 0) {{").ok();
            for g in &gated {
                for line in g.lines() {
                    writeln!(o, "    {line}").ok();
                }
            }
            writeln!(o, "    }}").ok();
        } else {
            for g in &gated {
                writeln!(o, "{g}").ok();
            }
        }
    }
    if has_ret {
        if m.type_layout(&ret)?.size == 8 {
            writeln!(
                o,
                "    tg_i386_set_eax(c, (uint32_t)(uint64_t)r);\n    tg_i386_set_edx(c, (uint32_t)((uint64_t)r >> 32));"
            )
            .ok();
        } else {
            writeln!(o, "    tg_i386_set_eax(c, (uint32_t)r);").ok();
        }
    }
    writeln!(o, "    return tg_end(k, 0);\n}}\n").ok();
    Ok(())
}

/// Emits the i386 forwarding.
pub fn emit(m: &mut Model) -> Result<I386Files, Error> {
    if !m.cfg.before.is_empty() || !m.cfg.after.is_empty() || !m.cfg.check.is_empty() {
        return Err(Error("hooks are not supported for an i386 guest".into()));
    }
    let sel = m.sel;
    let reg = m.reg;
    let cmds: Vec<(String, Vec<String>)> = sel
        .commands
        .iter()
        .filter(|(_, (_, a))| *a == Audience::Guest)
        .map(|(d, (n, _))| (d.clone(), n.clone()))
        .collect();
    for h in &m.cfg.hand_commands {
        if !cmds.iter().any(|(_, n)| n[0] == *h) {
            return Err(Error(format!("hand command {h} is not a selected command")));
        }
    }
    let mut o = String::new();
    writeln!(o, "{HEAD}\n{PRELUDE}").ok();
    writeln!(o, "static void *vki_fns[{}];", cmds.len().max(1)).ok();
    writeln!(
        o,
        "static const char *const vki_names[{}] = {{",
        cmds.len().max(1)
    )
    .ok();
    for (_, n) in &cmds {
        writeln!(o, "    \"{}\",", n[0]).ok();
    }
    writeln!(
        o,
        "}};\nstatic pthread_once_t vki_once = PTHREAD_ONCE_INIT;\n"
    )
    .ok();
    writeln!(
        o,
        "static void vki_bind(void)\n{{\n    for (uint32_t i = 0; i < {}; i++)\n        vki_fns[i] = tg_dlsym(\"{SONAME}\", vki_names[i], NULL);\n}}\n",
        cmds.len()
    )
    .ok();
    writeln!(
        o,
        "/** @brief The host function of command i; a missing one stops the program. */\nstatic void *vki_host(uint32_t i, const char *name)\n{{\n    pthread_once(&vki_once, vki_bind);\n    if (!vki_fns[i])\n        tg_fail(name, \"missing in the host library {SONAME}\");\n    return vki_fns[i];\n}}\n"
    )
    .ok();
    let conv: Vec<String> = m
        .converted
        .iter()
        .filter(|t| !dropped(m, t))
        .cloned()
        .collect();
    for t in &conv {
        if hand(m, t) {
            writeln!(o, "void vkih_in_{t}(tg_call *k, {t} *h, uint32_t g);").ok();
            writeln!(
                o,
                "void vkih_out_{t}(tg_call *k, uint32_t g, const {t} *h);"
            )
            .ok();
        } else {
            writeln!(
                o,
                "static inline void vki_in_{t}(tg_call *k, {t} *h, uint32_t g);"
            )
            .ok();
            writeln!(
                o,
                "static inline void vki_out_{t}(tg_call *k, uint32_t g, const {t} *h);"
            )
            .ok();
        }
        writeln!(
            o,
            "static inline {t} *vki_ain_{t}(tg_call *k, uint32_t g, uint64_t n);"
        )
        .ok();
        writeln!(
            o,
            "static inline void vki_aout_{t}(tg_call *k, uint32_t g, const {t} *h, uint64_t n);"
        )
        .ok();
    }
    writeln!(o).ok();
    for t in &conv {
        emit_struct(m, t, &mut o)?;
    }
    let mut stypes = Vec::new();
    for t in &sel.types {
        if let Some(Kind::Struct { members, .. }) = reg.types.get(t).map(|x| &x.kind)
            && let Some(v) = members.first().and_then(|f| f.values.clone())
            && !dropped(m, t)
        {
            stypes.push((t.clone(), v));
        }
    }
    writeln!(o, "static void *vki_chain_in(tg_call *k, uint32_t g)\n{{\n    while (g) {{\n        switch ((int32_t)tg_ld(k->mem + g, 4)) {{").ok();
    for (t, v) in &stypes {
        let conv_t = m.converted.contains(t);
        if conv_t {
            writeln!(
                o,
                "        case {v}: {{\n            {t} *h = tg_alloc(k, sizeof *h);\n            {}(k, h, g);\n            return h;\n        }}",
                in_fn(m, t)
            )
            .ok();
        }
    }
    writeln!(o, "        default:\n            fprintf(stderr, \"relift: vulkan: pNext structure type %d is not forwarded; skipped\\n\", (int)(int32_t)tg_ld(k->mem + g, 4));\n            g = (uint32_t)tg_ld(k->mem + g + 4, 4);\n        }}\n    }}\n    return NULL;\n}}\n").ok();
    writeln!(o, "static void vki_chain_out(tg_call *k, uint32_t g, const void *h)\n{{\n    while (g && h) {{\n        switch ((int32_t)tg_ld(k->mem + g, 4)) {{").ok();
    for (t, v) in &stypes {
        if m.converted.contains(t) {
            writeln!(
                o,
                "        case {v}:\n            {}(k, g, (const {t} *)h);\n            return;",
                out_fn(m, t)
            )
            .ok();
        }
    }
    writeln!(
        o,
        "        default:\n            g = (uint32_t)tg_ld(k->mem + g + 4, 4);\n        }}\n    }}\n}}\n"
    )
    .ok();
    for h in &m.cfg.hand_commands {
        writeln!(o, "uint64_t tgh_{h}(rl_ctx *c, uint8_t *mem);").ok();
    }
    writeln!(o).ok();
    for (i, (def, names)) in cmds.iter().enumerate() {
        if !m.cfg.hand_commands.contains(&names[0]) {
            emit_thunk(m, def, &names[0], i, &mut o)?;
        }
    }
    let mut all: Vec<(String, String)> = Vec::new();
    for (_, names) in &cmds {
        let f = if m.cfg.hand_commands.contains(&names[0]) {
            format!("tgh_{}", names[0])
        } else {
            format!("vki_{}", names[0])
        };
        for n in names {
            all.push((n.clone(), f.clone()));
        }
    }
    all.sort();
    writeln!(o, "static const tg_fn vki_table[{}] = {{", all.len()).ok();
    for (n, f) in &all {
        writeln!(o, "    {{\"{n}\", {f}}},").ok();
    }
    writeln!(o, "}};\n").ok();
    writeln!(
        o,
        "static void vki_load(void)\n{{\n    pthread_once(&vki_once, vki_bind);\n}}\n\nconst tg_lib tg_lib_vulkan = {{\"{SONAME}\", {}, vki_table, vki_load}};",
        all.len()
    )
    .ok();

    let mut lo = String::new();
    writeln!(
        lo,
        "{HEAD}\n/* Compile for i386 (-target x86-linux-gnu): the guest layouts. */\n#include \"vkg_types.h\"\n"
    )
    .ok();
    let structs: Vec<String> = m.structs.keys().cloned().collect();
    for t in &structs {
        let l = m.struct_layout(t)?;
        writeln!(
            lo,
            "_Static_assert(sizeof({t}) == {} && _Alignof({t}) == {}, \"{t} i386 layout\");",
            l.layout.size, l.layout.align
        )
        .ok();
        for (mem, off) in m.members(t).iter().zip(&l.offsets) {
            writeln!(
                lo,
                "_Static_assert(offsetof({t}, {}) == {off}, \"{t}.{} i386 offset\");",
                mem.name, mem.name
            )
            .ok();
        }
    }
    Ok(I386Files {
        thunks: o,
        layout: lo,
    })
}
