#[cfg(test)]
mod tests {
    use super::*;

    fn check(tsv: &str, dither: bool) {
        let mut seen = 0;
        for row in ROWS.iter().filter(|r| r.dither == dither) {
            let t = &THRESHOLDS[row.thresholds as usize..(row.thresholds + row.levels) as usize];
            let mut levels = Vec::new();
            for line in tsv.lines().filter(|l| l.starts_with("threshold ")) {
                let (head, bits) = line.split_once('\t').unwrap();
                let n: u32 = head.split(' ').nth(1).unwrap().parse().unwrap();
                if n == row.samples {
                    let b = u32::from_str_radix(bits.split('\t').next().unwrap(), 16).unwrap();
                    levels.push(f32::from_bits(b));
                }
            }
            let want: Vec<f32> = t.iter().map(|&k| k as f32 / 4096.0).collect();
            assert_eq!(levels, want, "{} samples", row.samples);
            for line in tsv.lines().filter(|l| l.as_bytes()[0].is_ascii_digit()) {
                let (head, masks) = line.split_once('\t').unwrap();
                let mut h = head.split(' ').map(|x| x.parse::<u32>().unwrap());
                let (n, a) = (h.next().unwrap(), h.next().unwrap());
                if n != row.samples {
                    continue;
                }
                let alpha = a as f32 / 255.0;
                let level = want.iter().filter(|&&w| alpha >= w).count() as u32;
                for (i, m) in masks.split(' ').enumerate() {
                    let (x, y) = (i as u32 % 8, i as u32 / 8);
                    let k = row.masks + level * 4 + (y & 1) * 2 + (x & 1);
                    assert_eq!(
                        u32::from_str_radix(m, 16).unwrap(),
                        MASKS[k as usize],
                        "{} samples, alpha {a}, pixel {i}",
                        row.samples
                    );
                }
                seen += 1;
            }
        }
        assert_eq!(seen, 4 * 256);
    }

    #[test]
    fn the_tables_are_the_measured_ones() {
        check(
            include_str!("../../../../runtime/tools/a2c_gl/rtx3090-dither-on.tsv"),
            true,
        );
        check(
            include_str!("../../../../runtime/tools/a2c_gl/rtx3090-dither-off.tsv"),
            false,
        );
    }
}
