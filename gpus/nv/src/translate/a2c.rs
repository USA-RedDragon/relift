//! The console GPU's alpha to coverage, as the RTX 3090 (NVIDIA 615.78.08)
//! gives it: the tables runtime/tools/a2c_gl measured with dither on (NVN's
//! default, the 2x2 footprint) and off (1x1), for 2, 4, 8 and 16 samples
//! (`rtx3090-dither-on.tsv`, `rtx3090-dither-off.tsv`; the Vulkan test
//! test_nvn_a2c.c measures the same dither-on table). Level `L` of a draw is
//! the number of its thresholds alpha is at or above, each `t / 4096`; pixel
//! `(x, y)` is covered by mask `L * 4 + (y & 1) * 2 + (x & 1)` of its row. A
//! test checks these against the measured tables.

